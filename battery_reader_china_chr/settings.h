  //  MISO. SPI.begin() кличеться один раз, тож назад воно вже не відіграє.
  //  Тому тут не #error (робоча конфігурація — не помилка), а попередження:
  //  переставите ініціалізацію місцями — розряд мовчки перестане керуватись.
