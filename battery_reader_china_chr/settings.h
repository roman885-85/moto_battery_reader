// ---------------------------------------------------------------------------
//  КЕРОВАНИЙ ЗАРЯД — ПОНИЖУВАЛЬНИЙ ПЕРЕТВОРЮВАЧ (buck) на біполярному PNP
// ---------------------------------------------------------------------------
//  ⚑ ЦЕ НЕ ПРОСТО КЛЮЧ. Після ключа стоїть діод на землю й дросель на вихід —
//  тобто класичний понижувач (step-down) із верхнім ключем. Дросель і діод
//  змінюють ФІЗИКУ настільки, що більшість «очевидних» рішень простого ключа
//  тут неправильні (див. «ЩО ЗМІНЮЄ ДРОСЕЛЬ» нижче).
//
//  ── СИЛОВА ЧАСТИНА ────────────────────────────────────────────────────────
//
//     +Uживл ─────┬──────[ R_підт ]──────┬─── E(емітер) PNP (B772M)
//                 │                      │
//                 └──────────────────────┴─── B(база) ──┐
//                                                        │
//     CHARGE_PWM_PIN ──[ R_драйв 470 ]── B(база)        │
//                                     NPN  C ────[ R_бази ]┘
//                                          E ── GND
//                       B ──[ R_вниз 10к ]── GND   <-- ОБОВ'ЯЗКОВО
//
//                     C(колектор) ─┬─────[ L дросель ]─────> +клема АКБ
//                                  │
//                            (катод) VD  діод Шотткі
//                                  │
//                                 GND
//
//  ⚑ КЛЮЧ — БІПОЛЯРНИЙ (B772M), А НЕ MOSFET. Це не «інша деталь у тій самій
//  ролі», а інший принцип: біполярник керується СТРУМОМ БАЗИ, а не напругою
//  на затворі. Наслідки, яких у MOSFET немає взагалі:
//
//   • R_бази (між колектором NPN і базою PNP) не «швидкодію налаштовує», а
//     ЗАДАЄ СТРУМ БАЗИ, від якого залежить, чи ключ узагалі насититься:
//     Iб = (Uживл − Uбе − Uке_нас_npn) / R_бази, і потрібно Iб >= Iк / β_форс
//     (β_форс ~20 для надійного насичення). Для 1 А це 50 мА бази й R ≈ 260 Ом,
//     причому НА САМОМУ РЕЗИСТОРІ розсіюється ~0.4 Вт — його треба брати на 1 Вт.
//     У MOSFET цей резистор струму не несе взагалі.
//
//   • Ключ ГРІЄТЬСЯ. У насиченні на ньому лишається Uке_нас ≈ 0.3…0.6 В (а не
//     мілівольти опору каналу), тож провідні втрати = Uке_нас × Iк × D. Плюс
//     біполярник вимикається ПОВІЛЬНО: заряд бази треба розсмоктати, і з
//     резистивним вимиканням це мікросекунди (у MOSFET — наносекунди).
//     Перевірка наприкінці блока рахує обидві складові й не дасть зібрати
//     прошивку з профілем струму, за якого B772M вийде за Pc.
//
//   • R_підт (база->емітер) тепер не «підтяжка затвора», а ЗАПИРАЮЧИЙ
//     резистор: він шунтує перехід база-емітер і прискорює розсмоктування.
//     Без нього вимикання ще повільніше. Типово 1…3 кОм.
//
//  ── ДРАЙВЕРНИЙ КАСКАД: КЕРУЮЧИЙ NPN ──────────────────────────────────────
//  Пін ESP32 НЕ керує силовим ключем напряму — між ними стоїть окремий
//  керуючий NPN, і в нього СВОЇ вимоги, бо він теж біполярний:
//
//   • Через його колектор тече ВЕСЬ струм бази PNP (86 мА). Це не «логічний
//     сигнал»: маленький сигнальний транзистор тут не підходить — BC547 із
//     його 100 мА максимуму працював би впритул. Потрібен 2N2222 / BC337 /
//     S8050.
//
//   • R_драйв (пін -> база NPN) задає струм бази САМОГО NPN:
//     Iб = (3.3 В − Uбе) / R_драйв. І тут та сама пастка, що з силовим
//     ключем: замалий струм -> NPN не в насиченні -> на ньому падає не
//     0.2 В, а вольт і більше -> струм бази PNP просідає -> З НАСИЧЕННЯ
//     ВИХОДИТЬ УЖЕ СИЛОВИЙ КЛЮЧ і згорає. Каскадний відмов.
//     Порахуємо: при 1 кОм струм бази NPN лише 2.6 мА, тобто β_форс = 33 —
//     межове насичення. При 470 Ом це 5.5 мА і β_форс = 16 — надійно.
//     Тому тут 470 Ом, а не «десь кілоом», і є перевірка наприкінці блока.
//
//   • Струм із піна (5.5 мА) з великим запасом уміщається в межі ESP32
//     (рекомендовані 20 мА на пін) — це теж перевіряється.
//
//  ЛОГІКА НЕ ІНВЕРТОВАНА — два інвертування взаємно скасовуються:
//    GPIO HIGH -> NPN відкритий -> струм витікає з бази PNP -> PNP ВІДКРИТИЙ;
//    GPIO LOW  -> NPN закритий  -> база підтягнута до емітера -> PNP ЗАКРИТИЙ.
//  Шпаруватість 0 % — безпечний стан.
//
//  !! РЕЗИСТОР 10 кОм З БАЗИ NPN НА ЗЕМЛЮ ОБОВ'ЯЗКОВИЙ — під час скидання й
//  завантаження ESP32 піни у високоімпедансному стані, база «висить», і без
//  нього наведення здатне прочинити ключ. Програмно це не перекрити.
//
//  ── ЩО ЗМІНЮЄ ДРОСЕЛЬ (і чому це не «просто ключ») ───────────────────────
//
//  1. ВИХІДНА НАПРУГА ЗАДАЄТЬСЯ ШПАРУВАТІСТЮ: Uвих ≈ D × Uживл. Це означає,
//     що струм у пакет з'являється ЛИШЕ коли D перевищить Uпакета/Uживл —
//     приблизно 0.6 при 8.4 В від 14 В. Нижче цього порога струму немає
//     взагалі. Тому soft-start «з нуля крок за кроком» тут не працює: до
//     робочої точки довелося б повзти сотні кроків. Регулятор стартує з
//     РОЗРАХОВАНОЇ шпаруватості, за якої вихід дорівнює напрузі пакета, —
//     це точка НУЛЬОВОГО струму, тобто так само безпечно, але одразу.
//
//  2. СТРУМ НЕ РВЕТЬСЯ. Дросель не дає струму стрибнути: у простому ключі
//     пік обмежували б лише різниця напруг і опір кола, а тут наростання
//     обмежене індуктивністю, і через шунт тече майже неперервний струм
//     дроселя з трикутними пульсаціями. Тому «пік» на шунті — це вершина
//     ПУЛЬСАЦІЙ (Iсер + ΔI/2), а не небезпечний кидок. Відсічка за піком
//     лишається як запобіжник (обрив дроселя, пробій ключа, насичення), але
//     її сенс саме такий.
//
//  3. ЧАСТОТА ШІМ МУСИТЬ БУТИ ВИСОКОЮ. Розмах пульсацій
//        ΔI = (Uживл − Uвих) × D / (L × f).
//     На 1 кГц зі 104 мкГн це десятки ампер — перетворювач працював би в
//     глибоко переривчастому режимі. Тому тут десятки кілогерц, а не 1 кГц,
//     як у розрядного ключа (той на резистор, йому дросель ні до чого).
//
//  4. ⚠️ АЛЕ ЗВЕРХУ ЧАСТОТУ ОБМЕЖУЄ САМ КЛЮЧ. Він БІПОЛЯРНИЙ (B772M), і
//     вимикається розсмоктуванням заряду бази — мікросекунди проти
//     наносекунд у MOSFET. Перемикальні втрати ½×Uживл×Iк×tsw×f ростуть
//     прямо з частотою й на 25 кГц уже переважають провідні (525 мВт проти
//     294 при 1 А). Тобто дросель тисне частоту вгору, ключ — униз, і 25 кГц
//     є компромісом. Перевірки наприкінці блока рахують і струм бази, і
//     розсіювання, і не дадуть зібрати прошивку з непосильною парою
//     «частота + профіль струму».
//
//  ── ВИМІРЮВАННЯ СТРУМУ ────────────────────────────────────────────────────
//
//     −клема АКБ ──┬──[ R_шунт 0.5 Ом ]── GND
//                  │
//                  └──[ 1 кОм ]── CHARGE_ISENSE_PIN
//
//  Спад на шунті нічого не ділить (нижнього резистора немає): 1 кОм — лише
//  струмообмеження входу АЦП на випадок кидка. Вхід високоомний, струму через
//  цей резистор практично немає, отже немає й падіння на ньому: на пін
//  приходить РІВНО напруга шунта, I × R_шунт (1 А -> 500 мВ).
//  ⚑ Саме тому 1 кОм не входить у жодну формулу перерахунку (chargeAdcMv()
//  у charge.h) — це не забутий доданок, і «виправляти» його не треба.
//
//  ⚑ Через шунт тече струм ДРОСЕЛЯ в ОБИДВІ фази (у відкритій — від живлення,
//  у закритій — по колу «дросель -> пакет -> шунт -> діод»), тож сигнал тут
//  майже неперервний. Серія відліків усереднює пульсації, а не «рубанину».
//
//  ⚠️ ШУНТ У МІНУСОВОМУ ПРОВОДІ. Під струмом «мінус» пакета піднімається над
//  землею ESP32 на I × 0.5 Ом — при 1.5 А це 750 мВ. Для 1-Wire (DS2433/
//  DS2438) це зсув опорної землі на чверть логічного рівня: читати монітор
//  ПІД СТРУМОМ не можна. Тому DS2438 читається лише на закритому ключі.
//
//  ⚠️ ПОТУЖНІСТЬ ШУНТА: I²R. При 1.5 А це 1.1 Вт — резистор потрібен від 2 Вт.
//  Він же з'їдає 0.75 В із бюджету напруги — це врахуйте, обираючи стелю
//  шпаруватості.
//
//  ── ВИМІРЮВАННЯ НАПРУГИ ───────────────────────────────────────────────────
//
//     +клема ──[ R_верх ]──┬──[ 1 кОм ]── CHARGE_VSENSE_PIN
//                          │
//                    [ R_низ ]
//                          │
//                         GND
//
//  1 кОм і тут лише струмообмеження входу — ділить пара R_верх/R_низ, а на
//  високоомному вході падіння на послідовному резисторі немає (див. вище).
//
//  Точка виміру — ПІСЛЯ дроселя, тобто напруга вже згладжена (і додатково
//  зафіксована самим пакетом). Прямокутника тут немає — на відміну від
//  простого ключа, де на клемі стрибала б напруга живлення.
//  Але під струмом до напруги пакета додається падіння на дротах і на його
//  внутрішньому опорі, тож для ЧЕСНОЇ напруги ключ усе одно коротко
//  закривається (CHARGE_VSENSE_SETTLE_MS) — так вимір лишається однаковим від
//  початку до кінця заряду.
//
//  ⚑ ПРО ЗАПАС ПОДІЛЬНИКА. Номінали — 20к зверху / 10к знизу, коефіцієнт 1:3.
//  У штатній роботі на клемі стоїть напруга ПАКЕТА, і вона лягає з великим
//  запасом: 8.25 В -> 2.75 В на піні при робочій стелі АЦП 3.1 В. Крок АЦП на
//  боці пакета — 2.4 мВ, точність надлишкова.
//
//  ⚠️ Є один НЕШТАТНИЙ випадок: якщо пакет від'єднати посеред заряду, на
//  клемі лишиться напруга ЖИВЛЕННЯ (дроселю нікуди віддавати струм), і
//  подільник дасть 14/3 ≈ 4.67 В — вище абсолютної межі входу 3.6 В.
//  Пін це переживає: вузол подільника має власний опір (20к∥10к = 6.7 кОм)
//  плюс послідовний 1 кОм, тож струм у захисний діод входу — лише ~139 мкА.
//  Саме тому послідовний резистор тут не косметика. Перевірка наприкінці
//  блока рахує цей струм за ВАШИМИ номіналами й не пропустить подільник із
//  замалим власним опором, де той самий випадок дав би вже міліампери.
//
//  ⚑ Раніше тут стояла порада «зменште нижнє плече до 2.7к». Вона була
//  ПОМИЛКОВОЮ: я виходив із того, що зверху 10к (тоді коефіцієнт був би 1:2,
//  і пакет 8.4 В дав би 4.2 В на піні). З реальними 20к зверху міняти нічого
//  не треба — 20к/10к і точніші, і безпечні.
//
//  Заряд ВИМКНЕНО, доки не задано всі три піни нижче.
// ---------------------------------------------------------------------------
// ⚠️ СПАДОК ПОПЕРЕДНЬОЇ СХЕМИ ЗАРЯДУ. До переробки на GPIO32 сидів
//  CHARGE_PIN — enable силового каскаду готової TL494-плати, і скетч
//  найпершим рядком setup() опускав його в LOW («вимкнено, безпечно»).
//  Переробка цей пін прибрала — і разом із ним прибрала й те, що його хтось
//  узагалі налаштовує. Тепер він просто ВИСИТЬ входом, а на платі до нього
//  цілком може лишатись припаяним той самий ланцюг: невизначений рівень на
//  вході чужої схеми — це саме той клас несправності, що з'являється «після
//  переробки» й виглядає як щось стороннє.
//  Тому пін і далі опускається в LOW при старті: якщо на платі до нього нічого
//  не припаяно — дія безкоштовна; якщо припаяно — відновлюється рівно той
//  стан, що був до переробки. Закоментуйте, коли переконаєтесь, що доріжка
//  зрізана.
#define CHARGE_LEGACY_EN_PIN 32

#define CHARGE_PWM_PIN    26   // ШІМ на базу NPN (той відкриває PNP-ключ)
#define CHARGE_ISENSE_PIN 35   // АЦП: спад на шунті 0.5 Ом у мінусовому проводі
#define CHARGE_VSENSE_PIN 34   // АЦП: напруга плюсової клеми через подільник
// ⚠️ ЦЕ НОВИЙ ВУЗОЛ. Подільник 68к/10к на GPIO39 треба спершу ЗІБРАТИ. Поки
//  його немає, пін висить у повітрі, читається як ~0 В, і заряд відхиляється з
//  «немає живлення» — тобто перевірка блокує те, що до неї працювало.
//  Розрізнити «давача немає» і «живлення немає» прошивка НЕ МОЖЕ: GPIO34..39
//  не мають внутрішніх підтяжок, тож розгойдати вільний пін і побачити різницю
//  ніяк.
//  ЗАКОМЕНТУЙТЕ цей рядок, доки подільник не зібрано: контроль живлення
//  вимкнеться, розрахунок піде на номінальних CHARGE_SUPPLY_MV, і заряд
//  працюватиме як до появи цієї перевірки.
#define CHARGE_PSU_PIN    39   // АЦП: напруга ЖИВЛЕННЯ (+14 В) через подільник

// ⚑ ЧОМУ САМЕ ЦІ ПІНИ.
//  35, 34 і 39 — ВХІД-ТІЛЬКИ (input-only) і належать до ADC1. Обидві
//  властивості тут доречні: вихідного драйвера в них немає взагалі, тож
//  вимірювальну лінію фізично неможливо випадково «продавити» назовні; а ADC1,
//  на відміну від ADC2 (GPIO 0,2,4,12-15,25-27), працює при УВІМКНЕНОМУ Wi-Fi —
//  а точка доступу в цьому проєкті активна завжди. На ADC2 вимірювання заряду
//  просто не читалися б.
//  26 звільнився від колишнього аналогового керування TL494-платою; GPIO25
//  звільнився від звуку (див. блок буззера вище) і лишається в резерві.
//
//  ⚑ ЩО ЩЕ ЛИШИЛОСЬ ВІЛЬНОГО з ADC1 (GPIO32..39) — на майбутнє:
//    • GPIO32 — ADC1_CH4, повноцінний пін (вхід/вихід). ⚠️ ЗАЙНЯТИЙ УМОВНО:
//      це колишній enable силового каскаду, і прошивка утримує його в LOW
//      (CHARGE_LEGACY_EN_PIN) — доки не переконаєтесь, що доріжку зрізано;
//    • GPIO36 (VP) — ADC1_CH0, теж вхід-тільки, повний аналог 39;
//    • GPIO37/38 фізично існують, але на переважній більшості модулів
//      ESP32-WROOM НЕ ВИВЕДЕНІ на гребінку — на них розраховувати не можна.
//  Зайняті з ADC1: 33 (драбинка кнопок), 34, 35 і тепер 39.
//  Для контролю живлення обрано саме 39, а не 32: 39 годиться ВИКЛЮЧНО як
//  аналоговий вхід, тоді як 32 уміє ще й бути виходом — витрачати його на
//  вимір означало б віддати єдиний універсальний пін, що лишився.

// ── КОНТРОЛЬ ЖИВЛЕННЯ +14 В ───────────────────────────────────────────────
//  Навіщо окремий вимір, якщо напруга живлення й так записана константою.
//  Саме тому й потрібен: CHARGE_SUPPLY_MV — це ПРИПУЩЕННЯ, на якому тримається
//  весь розрахунок (стартова шпаруватість D ≈ Uпак/Uживл, розмах пульсацій,
//  струм бази ключа, стеля шпаруватості). Якщо припущення не збігається з
//  дійсністю, прошивка про це не дізнається — вона просто мовчки регулюватиме
//  не туди:
//    • блока живлення немає взагалі -> заряд «іде» зі шпаруватістю в стелю й
//      нульовим струмом, і виглядає це як несправність пакета;
//    • стоїть 12-вольтовий блок -> струму бази ключа менше, стелі D може не
//      вистачити, щоб дотягнутись до цілі, і заряд упреться в стелю часу;
//    • стоїть 19-вольтовий від ноутбука -> ключ і пакет отримують помітно
//      більше, ніж закладено в усі перевірки вище.
//  Тому напруга живлення тепер ВИМІРЮЄТЬСЯ, а константа лишається запасним
//  значенням на випадок, коли пін не заданий.
//
//  Подільник — того ж стилю, що й на плюсовій клемі: верхнє плече, нижнє на
//  землю, і 1 кОм у сам пін як струмообмеження.
//    68к/10к: 14 В -> 1.79 В на піні, 20 В -> 2.56 В (усе ще в лінійній зоні).
//  Верхню межу взято з запасом саме для того, щоб ПОМИЛКОВИЙ блок на 19 В
//  читався числом, а не «залипав» на 4095.
#define CHARGE_PSU_R_TOP        68000
#define CHARGE_PSU_R_BOT        10000
#define CHARGE_PSU_R_SERIES     1000
// Найвища напруга живлення, яку прошивка мусить ЧИТАТИ ТОЧНО, мВ (вище —
// показання можуть залипати, але то вже однозначна аварія).
#define CHARGE_PSU_MAX_READ_MV  20000

//  ── ПОРОГИ ────────────────────────────────────────────────────────────────
//  Нижче цього вважаємо, що блока живлення НЕМАЄ взагалі.
//  ⚠️ Нуля тут може й не бути. Якщо пакет під'єднано, а блок вимкнено, пакет
//  підживлює шину живлення ЧЕРЕЗ ПЕРЕХІД БАЗА-КОЛЕКТОР силового PNP (база
//  притягнута до емітера запираючим резистором, а на колекторі стоїть напруга
//  пакета через дросель) — на шині опиняється Uпак мінус діодне падіння.
//  Тому поріг «немає живлення» піднято до 6 В: усе, що нижче найнижчого
//  розрядженого пакета, живленням бути не може.
#define CHARGE_PSU_ABSENT_MV    6000
//  Робочий діапазон. Нижче мінімуму — «не той блок живлення / напруга
//  занижена»: заряд не стартує, а той, що йде, зупиняється.
#define CHARGE_PSU_MIN_MV       12500
//  Вище максимуму — теж не той блок (типово 19 В від ноутбука).
//  ⚑ Обидва пороги ПІДТВЕРДЖЕНІ ВЛАСНИКОМ, це не оцінка «на око». Верхній
//  впливає не лише на діагностику: саме він задає CHARGE_NPN_BASE_OHM, бо
//  струм драйвера росте разом із живленням (при 16 В — 124 мА, звідси 390 Ом;
