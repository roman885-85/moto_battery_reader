  #define CHARGE_MOS_IDIV_AT_MAX_PSU_UA \
      (((CHARGE_PSU_MAX_MV) - (CHARGE_NPN_VCE_SAT_MV)) * 1000 / \
       ((CHARGE_BASE_DRIVE_OHM) + (CHARGE_BASE_PULLUP_OHM)))

  //  ЧАС ПЕРЕМИКАННЯ. У польового його задає не даташит, а НАШ драйвер: скільки
  //  струму він дає в затвор, за такий час і перезарядить Qg.
  //   • ВМИКАННЯ: затвор тягне вниз дільник, його опір — паралельне з'єднання
  //     плечей. Струм спадає від початкового до нуля, тож беремо половину.
  //   • ВИМИКАННЯ повільніше, і це головне: вгору затвор тягне ЛИШЕ підтяжка.
  //     Струм падає від (Uживл − Uзатв_вкл)/R_підт на початку до
  //     (Uживл − Uзатв_вимк)/R_підт у момент закриття; беремо середнє.
  #define CHARGE_MOS_RG_ON_OHM \
      ((CHARGE_BASE_DRIVE_OHM) * (CHARGE_BASE_PULLUP_OHM) / \
