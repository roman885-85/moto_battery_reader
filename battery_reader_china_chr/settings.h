//
//  ⚑ ЦЕ БІЛЬШЕ НЕ ДОРІВНЮЄ BATTERY_FULL_MV, і розчеплення тут навмисне.
//  BATTERY_FULL_MV (8250) — це «100 %» ШКАЛИ ПАЛИВОМІРА: за нею рахуються
