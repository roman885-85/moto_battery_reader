//
//  ⚠️ НАСЛІДОК, ЯКИЙ ТРЕБА ЗНАТИ ЗАЗДАЛЕГІДЬ: наприкінці успішного заряду
//  паливомір покаже не 100 %, а ~97 % — бо 8200 мВ на шкалі 6350…8250 це саме
