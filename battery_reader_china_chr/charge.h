// ⚑ «ЗАВЕРШЕНО» — ЦЕ МНОЖИНА, А НЕ ОДНЕ ЗНАЧЕННЯ. Заряд доходить до кінця
//  двома різними шляхами: або ми самі побачили цільову напругу (CHGR_TARGET),
//  або пакет дійшов до своєї межі й розімкнув себе першим (CHGR_PACKFULL).
//  Другий шлях — штатний і навіть частіший: захист пакета стежить за
//  НАЙВИЩОЮ банкою, а ми міряємо суму, тож при найменшому розбігу банок він
//  спрацює раніше за нас. Порівняння «reason == CHGR_TARGET» в одному місці й
//  «reason != CHGR_TARGET» в іншому неминуче розійшлись би, тому питання
//  ставиться рівно в одній функції.
inline bool chargeReasonIsDone(uint8_t r) {
    // CHGR_WOKE — успіх ПРОБУДЖЕННЯ, і потрапляє він сюди з тієї ж причини, що
    // й CHGR_PACKFULL: режим досяг рівно того, заради чого його запускали.
    return r == CHGR_TARGET || r == CHGR_PACKFULL || r == CHGR_WOKE;
}

inline void chargeStop(uint8_t reason) {
    // Ключ гасимо ЗАВЖДИ — безумовний запобіжник, він нікому не шкодить.
    chargeOff();
    g_chg.duty = 0;
    // Стелю сеансу — теж завжди й теж безумовно. Вона могла бути опущена
    // пробудженням, і лишити її опущеною означало б покалічити наступний
    // штатний заряд (він упреться в чужу стелю й спиниться за «ключ не тягне»).
    chargeResetDutyCap();

    // ⚑ РЕШТА — ЛИШЕ ЯКЩО ЗАРЯД СПРАВДІ ЙШОВ (дзеркально до dischargeStop(),
    // де це розписано докладно). Коротко: зупинку кличуть ззовні беззастережно
    // (кнопка, /api/charge/stop, «CHARGE STOP» по USB), а повне згортання знімає
    // апаратного сторожа й сигнал enable — спільні для обох операцій. Виконане
    // «вхолосту», воно розвалює РОЗРЯД, що саме йде.
    if (g_chg.state != CHG_RUN) return;

    chargeWatchdog(false);
    g_chgReleaseEnable = true;
    chargeMarkDirty(2);
    g_chg.state  = chargeReasonIsDone(reason) ? CHG_DONE : CHG_ABORT;
    g_chg.reason = reason;
    ledSet(chargeReasonIsDone(reason) ? LED_OK : LED_ERROR);
}

