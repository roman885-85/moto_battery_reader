// ── ДВІ ВІДСІЧКИ, ЯКІ МУСЯТЬ БУТИ ПЕРЕВІРЯЮВАНИМИ ─────────────────────────
//  Обидві живуть ТУТ, а не в chargeTask() у web_server.h, і на це є причина.
//  web_server.h на хості не збирається взагалі (WebServer, SPIFFS, U8g2,
//  ArduinoJson), тож усе, що написано всередині chargeTask(), не покрите
//  жодним тестом. Раніше в цьому проєкті вже був тест, що тримав ВЛАСНУ КОПІЮ
//  логіки заряду й лишався зеленим після переробки схеми, — повторювати цю
//  помилку не можна. Тому рішення «зупинятись чи ні» ухвалюють ось ці дві
//  функції, які тест викликає напряму, а chargeTask() лишається тонким
//  викликачем: він тільки міряє, питає й виконує.
//
//  Лічильник передається за посиланням: обидві відсічки рахують СТАЛИЙ стан, а
//  не поодинокий провал, і скидаються на першому ж нормальному опитуванні.

// ── ТРЕТЯ ВІДСІЧКА: ПОКАЗАННЯ ВИЙШЛО ЗА МЕЖІ ВИМІРЮВАНОГО ─────────────────
//  Скарга, з якої це народилось: «при досягненні максимального заряду пише
//  напруга 9.9 В, аварійна зупинка, перенапруга».
//
//  9.9 В — це НЕ виміряна напруга. Це рівно те число, яке видає ланцюжок
//  перерахунку, коли АЦП уперся в стелю:
//
//      chargeAdcMv()  = 4095 * CHARGE_ADC_FULL_MV / CHARGE_ADC_MAX_RAW
//                     = 4095 * 3300 / 4095            = 3300 мВ
//      chargePackMv() = 3300 * (R_TOP + R_BOT) / R_BOT
//                     = 3300 * 30000 / 10000          = 9900 мВ
//
//  Тобто «9.9 В» — це підпис відліку 4095, а не напруга на клемі. Про саме
//  залипання в settings.h написано прямо (біля CHARGE_ADC_MAX_MV), але
//  прошивка все одно брала залиплу цифру за напругу пакета й оголошувала
//  перенапругу. Діагноз був неправильний: 2-банковий (6-елементний) пакет
//  IMPRES фізично не буває під 9.9 В — повний це 8.25 В.
//
//  Що насправді означає впертий у стелю вхід: на плюсовій клемі стоїть
//  НАПРУГА ЖИВЛЕННЯ, а не напруга пакета. Пакета на клемі немає — коло
//  розімкнене, і подільник показує шину +14 В через відкритий ключ або через
//  витік. Причини за спаданням імовірності:
//    • втрачено контакт із пакетом (клема, пружина, окислення);
//    • знято enable — немає обов'язкового резистора 4.7 кОм на +3.3 В або
//      рівень просів (див. PULLUP_PIN у settings.h);
//    • пакет від'єднався сам своїм внутрішнім захистом.
//
//  Поріг береться від СТЕЛІ ТОЧНОГО ВИМІРУ (CHARGE_ADC_MAX_MV), а не від
//  стелі перерахунку: між 9.3 і 9.9 В показання вже недостовірні, і вірити їм
//  як напрузі не можна незалежно від того, залипли вони остаточно чи ні.
//  Число не пишеться руками — воно виводиться з подільника, інакше зміна
//  номіналів тихо зсунула б відсічку. Перевірки в settings.h стежать, щоб
//  поріг лишався ВИЩЕ аварійної межі й НИЖЧЕ найбільшого можливого показання.
inline bool chargeSenseSaturated(uint16_t mv) {
#ifdef CHARGE_VSENSE_PIN
    return mv >= (uint16_t)CHARGE_VSENSE_SAT_MV;
#else
    (void)mv; return false;
#endif
}

// І та сама відсічка з витримкою — рівно як у двох сусідніх.
//  chargePackMv() робить ОДИН analogRead() без усереднення, тож зупиняти
//  багатогодинний заряд по одному відліку не можна: сусідні дві відсічки
//  рахують сталий стан саме тому. Тут вистачає двох опитувань (2 с) — довше
//  тягнути нема сенсу, бо на клемі в цей час стоїть напруга живлення.
// ⚑ Тут колись стояла chargeNoPackTrip() — та сама витримка, але з єдиною
//  відповіддю «пакета немає». Її замінила пара chargeSatWitness()/
//  chargeSatTripped() нижче: витримка лишилась ТА САМА, а от відповідей стало
//  чотири. Другого лічильника поруч не тримаємо навмисне — два майже однакові
//  механізми з різними висновками неминуче розійшлися б, і живий залишився б
//  не той.

// ── ЧОМУ САМЕ КЛЕМА В СТЕЛІ: ЧОТИРИ РІЗНІ ВІДПОВІДІ ───────────────────────
//  Спостереження власника: дійшовши до 8.2 В, пакет розмикає власний захист.
//  Зовні це не відрізнити від загубленого контакту — в обох випадках на клемі
//  лишається живлення, а подільник іде в стелю. Але за суттю це протилежні
//  події: перша означає «заряд завершено», друга — «аварія».
//
//  Свідок, який їх розрізняє, у схемі вже є. Монітор DS2438 сидить УСЕРЕДИНІ
//  пакета: живиться від банок, спілкується власною лінією даних і тому НЕ
//  залежить від силового ключа пакета. Витягнули пакет — монітор мовчить.
//  Пакет на місці, лише закрив себе сам — монітор відповідає й називає
//  справжню напругу банок, поки клема бреше.
//
//  Звідси чотири результати, і кожен веде до свого діагнозу:
//    GONE — монітор мовчить: пакета в колі фізично немає (аварія, як і було);
//    FULL — монітор живий і показує ~ціль: пакет повний, заряд ЗАВЕРШЕНО;
//    OPEN — монітор живий, але напруга далеко не цільова: захист спрацював не
//           за напругою (банка, температура, струм) — це несправність пакета,
//           і мовчки записувати її в «успішно заряджено» не можна;
//    OVER — монітор живий і показує ВИЩЕ аварійної межі: справжня перенапруга,
//           уперше виміряна зсередини. Саме цей випадок раніше не мав жодного
//           способу проявитися, бо зовнішній подільник у стелі однаковий для
//           всіх чотирьох.
enum {
    SATV_GONE = 0,
    SATV_FULL,
    SATV_OPEN,
    SATV_OVER,
};

inline uint8_t chargeSatVerdict(bool chipOk, uint16_t chipMv, uint16_t targetMv) {
    if (!chipOk) return SATV_GONE;
    if ((uint32_t)chipMv >= (uint32_t)targetMv + CHARGE_HARD_MAX_HEADROOM_MV)
        return SATV_OVER;
    if ((uint32_t)chipMv + CHARGE_PACKFULL_TOL_MV >= (uint32_t)targetMv)
        return SATV_FULL;
    return SATV_OPEN;
}

// Накопичення свідчень за епізод «клема в стелі». Викликається КОЖНЕ
// опитування, і саме воно, а не окремий вимір, тримає стан епізоду:
// лічильник опитувань разом із найкращим, що вдалось почути від монітора.
inline void chargeSatWitness(uint16_t mv, bool chipFresh, uint16_t chipMv,
                             uint8_t *polls, bool *chipOk, uint16_t *satMv) {
    if (!chargeSenseSaturated(mv)) {          // клема повернулась до тями —
        *polls = 0; *chipOk = false; *satMv = 0;   // епізод закінчився, слід стерти
        return;
    }
    if (*polls < 255) (*polls)++;
    if (chipFresh) { *chipOk = true; *satMv = chipMv; }
}

// Витримка: chargePackMv() робить ОДИН analogRead() без усереднення, тож
// вирішувати долю багатогодинного заряду за одним відліком не можна. Двох
// опитувань (2 с) досить — довше тягнути нема сенсу, бо коло вже розімкнене.
inline bool chargeSatTripped(uint8_t polls) { return polls >= CHARGE_NOPACK_POLLS; }

// Живлення поза допуском CHARGE_PSU_BAD_POLLS опитувань поспіль.
//  Одиничний вихід за межі — це просадка на кидку струму, а не аварія.
inline bool chargePsuTrip(uint8_t psuState, uint8_t *polls) {
    if (psuState == PSU_OK || psuState == PSU_UNKNOWN) { *polls = 0; return false; }
    if (*polls < 255) (*polls)++;
    return *polls >= CHARGE_PSU_BAD_POLLS;
}

// «Ключ не тягне»: шпаруватість уперлась у стелю, а струм усе одно нижчий за
// CHARGE_NODRIVE_PCT від уставки — і так CHARGE_NODRIVE_POLLS разів поспіль.
//
// ⚑ Навіщо взагалі зупинятись, якщо струму МАЛО (а не багато). Бо реакція
// регулятора на брак струму — піднімати шпаруватість, тобто збільшувати час,
// який транзистор проводить під навантаженням. Якщо причина браку — замалий
// струм бази (ключ поза насиченням), це рівно те, що його й палить. Стеля
// часу спрацює через шість годин, коли палити вже нічого.
inline bool chargeNoDriveTrip(uint16_t duty, int32_t avgMa, uint16_t setMa,
                              uint8_t *polls) {
    if (avgMa < 0) avgMa = 0;
    bool starved = (duty >= CHARGE_DUTY_MAX) && (setMa > 0) &&
                   ((uint32_t)avgMa * 100u < (uint32_t)setMa * CHARGE_NODRIVE_PCT);
    if (!starved) { *polls = 0; return false; }
    if (*polls < 255) (*polls)++;
    return *polls >= CHARGE_NODRIVE_POLLS;
}

// ═════════════ ПРИМУСОВЕ ПРОБУДЖЕННЯ КОНТРОЛЕРА ПАКЕТА ════════════════════
//  ЗАДАЧА. Після заміни елементів пакет не читається взагалі: контролер
//  захисту всередині заблокований (глибокий розряд перед заміною або просто
//  знеструмлення на час паяння) і не відпускає клеми, доки не побачить
//  зовнішню зарядну напругу. Поки він мовчить, мовчать і DS2438 з DS2433 —
//  а штатний заряд саме через це й відмовляє: без DS2438 немає температури.
//  Замкнене коло: щоб зарядити, треба прочитати; щоб прочитати, треба подати
//  напругу. Цей режим його розриває.
//
//  ── ЧОМУ ЦЕ НЕ «ЗАРЯД БЕЗ ТЕМПЕРАТУРИ» ───────────────────────────────────
//  Заборона заряджати наосліп лишається чинною й нікуди не дівається. Тут
//  дозвіл спирається не на послаблення правила, а на ЕНЕРГІЮ: режим фізично
//  не здатен віддати більше за CHARGE_WAKE_MAH_MAX (перевірка в settings.h
//  тримає це нижче 1 % паспортної ємності) і живе лічені хвилини. Нагріти
//  пакет такою енергією за такий час неможливо в принципі — тому датчик і не
//  потрібен. Заберіть будь-яку з цих меж — і обґрунтування зникне разом із
//  нею; саме тому кожна перевіряється на компіляції.
//
//  ── ГОЛОВНЕ РІШЕННЯ: ЦЕ ДЖЕРЕЛО НАПРУГИ, А НЕ СТРУМУ ─────────────────────
//  Штатний заряд тримає СТРУМ, бо пакет у колі є й він цей струм бере. Тут
//  пакет із кола вимкнений власним ключем — струму немає й бути не може.
//  Струмовий регулятор, не бачачи струму, підіймав би шпаруватість крок за
//  кроком, поки не впреться в заводську стелю 85 %, тобто виклав би на клеми
//  ~11.9 В. І рівно тієї миті, коли контролер прокинеться й замкне ключ, ці
//  11.9 В опинилися б на банках 2S. Тому регулюється НАПРУГА — через стелю
//  шпаруватості (chargeSetDutyCap), — а струм лишається верхнім обмеженням.
//
//  ── ЧОМУ НАПРУГУ НЕ МІРЯЮТЬ, А РАХУЮТЬ ───────────────────────────────────
//  Після дроселя немає ні навантаження, ні згладжувальної ємності: її роль у
//  цій схемі грає сам пакет (див. схему в settings.h — конденсатора там
//  немає). Вимкнений пакет = розімкнене коло = на подільнику дзвін, а не
//  напруга. Тому напругу задають наперед, стелею шпаруватості за Uвих ≈ D ×
//  Uживл, а МІРЯЮТЬ її лише на закритому ключі — раз на CHARGE_WAKE_PROBE_S,
//  разом зі спробою докликатись монітора.

// Стеля шпаруватості для пробудження: та, за якої ідеальний понижувач дає
// CHARGE_WAKE_MV. Живлення приймаємо параметром, а не беремо з глобальної
// змінної, щоб цю арифметику можна було ганяти на хості для будь-якого блока.
inline uint16_t chargeWakeDutyCapFor(uint16_t supplyMv) {
    if (!supplyMv) return 0;
    uint32_t d = (uint32_t)CHARGE_WAKE_MV * CHARGE_DUTY_FULL / supplyMv;
    if (d > CHARGE_DUTY_MAX) d = CHARGE_DUTY_MAX;
    return (uint16_t)d;
}
inline uint16_t chargeWakeDutyCap() { return chargeWakeDutyCapFor(chargeSupplyMv()); }

// Наступна шпаруватість пробудження. Крок пропорційний похибці струму — з тієї
// ж причини, що й у штатного регулятора, — але затиснутий CHARGE_WAKE_STEP, бо
// тут крок за шпаруватістю це крок за НАПРУГОЮ на клемах.
//
// ⚑ dutyCap НЕ порада, а межа: результат затискається нею в КОЖНІЙ гілці,
// включно з тією, що йде вниз. Інакше стеля, опущена посеред сеансу (живлення
// піднялось -> та сама шпаруватість дає більшу напругу), лишила б у g_chg.duty
// число вище чинної межі — і на екрані стояло б одне, а на ключі інше.
inline uint16_t chargeWakeNextDuty(uint16_t duty, int32_t avgMa, uint16_t dutyCap) {
    // Мінус — це шум навколо нуля або розряд, і в обох випадках струму заряду
    // немає. Випрямляти його означало б вдавати, ніби стеля вже досягнута.
    if (avgMa < 0) avgMa = 0;
    if (dutyCap > CHARGE_DUTY_MAX) dutyCap = CHARGE_DUTY_MAX;

    int32_t err  = (int32_t)CHARGE_WAKE_MA - avgMa;    // + = струму ще бракує
    int32_t mag  = err < 0 ? -err : err;
    int32_t step = mag / CHARGE_DUTY_MA_PER_STEP;
    if (step < 1)                step = 1;
    if (step > CHARGE_WAKE_STEP) step = CHARGE_WAKE_STEP;

    uint32_t d = duty;
    if      (err < -(int32_t)CHARGE_DEADBAND_MA) d = (duty > step) ? (uint32_t)(duty - step) : 0u;
    else if (err >  (int32_t)CHARGE_DEADBAND_MA) d = (uint32_t)duty + step;
    // інакше — мертва зона: стоїмо, як і штатний регулятор.

    if (d > dutyCap) d = dutyCap;
    return (uint16_t)d;
}

// Те, що бачить машина пробудження за один прохід.
struct ChargeWakeIn {
    bool     chipOk;     // монітор ВІДПОВІВ саме цього проходу
    uint16_t avgMa;      // середній струм через шунт
    bool     mvFresh;    // напругу міряли на ЗАКРИТОМУ ключі цього проходу
    uint16_t mv;         // і ось вона (інакше поле не дивимось)
    uint32_t elapsedS;   // від старту режиму
    uint32_t mah;        // скільки вже віддано, мА·год
};

enum {
    WAKEV_GO = 0,     // нічого не сталося — тримаємо напругу далі
    WAKEV_WOKE,       // монітор відповів: мета досягнута
    WAKEV_OVERI,      // середній струм пішов угору — відмова регулятора
    WAKEV_OVERV,      // на клемі напруга вище дозволеної
    WAKEV_MAH,        // вичерпано стелю відданої ємності
    WAKEV_TIMEOUT,    // вичерпано стелю часу
};

// ⚑ ПОРЯДОК ТУТ ВИРІШУЄ ЛИШЕ НАЗВУ ПОДІЇ, А НЕ БЕЗПЕКУ: будь-який вирок,
//  крім WAKEV_GO, однаково гасить ключ, а запобіжник заліза (піковий струм)
//  стоїть окремо й спрацьовує ще до цієї функції. Тому «монітор відповів» іде
//  ПЕРШИМ, і це не поблажливість: стрибок струму в мить пробудження —
//  ОЧІКУВАНА подія (контролер замикає ключ, і на місці розімкненого кола
//  раптом з'являється навантаження). Поставити відсічку за струмом вище
//  означало б із високою ймовірністю назвати аварією саме те, заради чого
//  режим і запускали, — і користувач ганяв би пробудження по колу, щоразу
//  отримуючи «відмова регулятора» замість «готово».
inline uint8_t chargeWakeVerdict(const ChargeWakeIn &in) {
    if (in.chipOk) return WAKEV_WOKE;
    if (in.avgMa > CHARGE_WAKE_MA_ABORT) return WAKEV_OVERI;
    // ⚑ НАСИЧЕНИЙ ВІДЛІК ТУТ — НЕ ПЕРЕНАПРУГА, А НОРМА. У штатному заряді
    //  клема в стелі означає «коло розімкнулось» і веде до аварії; у
    //  пробудженні розімкнене коло — це ВИХІДНИЙ стан, з якого режим і
    //  починається. Пропустити насичення в порівняння з порогом означало б
    //  обривати пробудження на першій же пробі, тобто зробити режим
    //  непрацездатним рівно в тому випадку, для якого він написаний.
    //  Пробитий ключ (єдина справжня біда, що теж дає стелю) ловиться до
    //  старту — chargeWakeRefuse() бачить і напругу, і струм на закритому
    //  ключі, коли через дросель ще нічого не текло.
    if (in.mvFresh && !chargeSenseSaturated(in.mv) &&
        (uint32_t)in.mv >= (uint32_t)CHARGE_WAKE_MV + CHARGE_HARD_MAX_HEADROOM_MV)
        return WAKEV_OVERV;
    if (in.mah      >= (uint32_t)CHARGE_WAKE_MAH_MAX) return WAKEV_MAH;
    if (in.elapsedS >= (uint32_t)CHARGE_WAKE_MAX_S)   return WAKEV_TIMEOUT;
    return WAKEV_GO;
}

// Вирок -> причина зупинки. Окремою функцією, бо це саме ПЕРЕКЛАД: причини
// живуть у спільному переліку CHGR_*, який читають екран, веб і USB-клієнт.
inline uint8_t chargeWakeReason(uint8_t verdict) {
    switch (verdict) {
        case WAKEV_WOKE:    return CHGR_WOKE;
        case WAKEV_OVERI:   return CHGR_WAKE_OVERI;
        case WAKEV_OVERV:   return CHGR_HARD_MAX;
        case WAKEV_MAH:     return CHGR_WAKE_MAH;
        case WAKEV_TIMEOUT: return CHGR_WAKE_FAIL;
        default:            return CHGR_NONE;
    }
}

// ── ЧОМУ ПРОБУДЖЕННЯ МОЖУТЬ НЕ ДАТИ ───────────────────────────────────────
//  Умови зібрані в чисту функцію з тієї ж причини, що й дві відсічки вище:
//  chargeWakeStart() живе у web_server.h, який на хості не збирається взагалі,
//  тож усе написане всередині нього не покриває жоден тест.
enum {
    WAKENO_OK = 0,
    WAKENO_NA,      // заряд не налаштовано (немає пінів)
    WAKENO_PWM,     // ШІМ не прикріпився — керувати ключем нічим
    WAKENO_BUSY,    // заряд або розряд уже йде
    WAKENO_PSU,     // живлення +14 В поза допуском
    WAKENO_READS,   // пакет ЧИТАЄТЬСЯ — будити нема кого
    WAKENO_RAIL,    // на ЗАКРИТОМУ ключі клема в стелі — ключ пробитий
    WAKENO_LEAK,    // на ЗАКРИТОМУ ключі шунт бачить струм — ключ пробитий
    WAKENO_FULL,    // на клемі вже є напруга, не нижча за напругу пробудження
};

// ⚑ WAKENO_READS — ГОЛОВНА З УСІХ. Пробудження працює без контролю
//  температури, і єдине, що не дає перетворити його на «заряд без датчика», —
//  це відмова запускатись, коли датчик доступний. Пакет читається -> є
//  температура -> є штатний заряд, і жодних підстав обходити його немає.
inline uint8_t chargeWakeRefuse(bool available, bool pwmOk, bool busy, uint8_t psu,
                                bool chipReads, uint16_t mv, uint16_t idleMa) {
    if (!available)  return WAKENO_NA;
    if (!pwmOk)      return WAKENO_PWM;
    if (busy)        return WAKENO_BUSY;
    if (psu != PSU_OK && psu != PSU_UNKNOWN) return WAKENO_PSU;
    if (chipReads)   return WAKENO_READS;
    // Обидві ознаки пробитого ключа. Міряються ДО того, як через дросель щось
    // потекло, тож тлумачаться однозначно: живлення на клемі при закритому
    // ключі й струм при закритому ключі можуть означати лише коротке в ключі.
    if (chargeSenseSaturated(mv))    return WAKENO_RAIL;
    if (idleMa > CHARGE_DEADBAND_MA) return WAKENO_LEAK;
    if (mv >= (uint16_t)CHARGE_WAKE_MV) return WAKENO_FULL;
    return WAKENO_OK;
}

