// Нижня межа шпаруватості, %. Нижче — вважаємо, що навантаження не потрібне
// взагалі (захист від «майже закритого» ключа, де він працює лінійно).
#define DISCHARGE_DUTY_MIN_PCT 3

// Скільки тримати ключ ПОВНІСТЮ відкритим перед зняттям показань, мс.
//  Навіщо. DS2438 віддає миттєвий струм останнього перетворення (~27 мс). На
