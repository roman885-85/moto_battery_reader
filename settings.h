// ⚠️ ТЕКСТ шкали — ПОРУЧ із числами, і більше ніде.
//
// Раніше нижня точка шкали стояла літералами в десятку місць: у меню пристрою, у
// підказках веба, USB-клієнта, ехе-клієнта, у Майстрі й у коментарях. Варто
// було раз змінити число — і частина написів лишалась брехати: у діалозі
// ехе-клієнта до останнього висіли 7.0/8.4 В від ще давнішої шкали. Тепер усі
// поверхні беруть рядок звідси, а окремий тест звіряє його з
// числами вище.
#define BATTERY_SCALE_TXT       "6.35 В = 0 %, 8.25 В = 100 %"
#define BATTERY_SCALE_TXT_SHORT "6.35В=0% 8.25В=100%"
// Струмовимірювальний резистор DS2438, Ом — ⚑ ЛИШЕ ЗАПАСНЕ ЗНАЧЕННЯ.
//
// Кожен пакет носить СВІЙ відкалібрований шунт прямо в чипі: DS2438[56..57],
// два байти LE, значення/100000 = Ом (impres_bms.h, розділ 4a.2 документа).
// Прошивка тепер читає його звідти, а сюди падає лише коли поле порожнє —
// наприклад, на занулених чипах.
//
// Чому це важливо. У наших дампах шунт у PMNN4409A/B — 0.045..0.046 Ом, а в
// 4488A/4493A/4809A — 0.025..0.026 Ом. Тобто стара єдина константа 0.025
// занижувала опір на родині 4409 майже вдвічі, а отже завищувала і струм, і
// мА·год у 1.8 раза. Для керованого розряду це не косметика: уставка ШІМ
// тримає саме ВИМІРЯНИЙ струм.
#define DS2438_RSENSE_OHM 0.025f
// Ціна молодшого розряду ICA в мА·год (даташит DS2438): 0.4882/Rsense.
// ⚠️ Це крок ЛИШЕ для ICA. У CCA/DCA крок 15.625 мВ·год — у 32 рази більший;
// для них рахунок ведеться в impres_bms.h / discharge.h, не тут.
// Живого коду за цими двома макросами вже немає (шунт беруть із чипа) —
// лишені для сумісності з зовнішніми скриптами.
#define DS2438_MAH_PER_LSB (0.4882f / DS2438_RSENSE_OHM)
// Паспортна ємність АКБ, мА·ч — для підрахунку циклів заряду/розряду:
// 1 цикл = сумарний заряд (розряд), рівний однієї повної ємності.
// Вкажіть ємність вашої батареї (PMNN4409 — 2500, PMNN4493 — 3000 і т.п.).
#define BATTERY_RATED_MAH 2500
// Повна шкала ICA (залишкової ємності DS2438), мА·ч: ICA=255 -> стільки мА·ч.
// Використовується для показу/редагування залишкової ємності в мА·ч (замість відсотків).
#define ICA_FULL_MAH (255.0f * DS2438_MAH_PER_LSB)

// ---------------------------------------------------------------------------
//  КЕРОВАНИЙ ЗАРЯД — DC/DC на P-канальному MOSFET (понижуючий/buck)
// ---------------------------------------------------------------------------
//  Схема (зібрана власником, поза цим проєктом): вхід ~14 В (штатний блок
//  живлення IMPRES) -> P-канальний MOSFET -> дросель -> АКБ, зворотний діод
//  із виходу дроселя на землю. P-канальний ключ ЗВЕРХУ (між входом і
//  дроселем) — типова топологія понижуючого перетворювача: ключ відкритий ->
//  вхід тягне струм через дросель у пакет; ключ закритий -> струм дроселя
//  тече далі через діод. Шпаруватість керує НАПРУГОЮ на дроселі, а не струмом
//  напряму — тому регулятор нижче працює інакше, ніж у розряду (там ключ на
//  резисторі, і струм рахується з нього алгебрично).
//
//  ПОЛЯРНІСТЬ КЕРУВАННЯ — підтверджена власником схема, два транзистори:
//    • Т1 (у стані спокою ПРОВІДНИЙ) з'єднує затвор із +14 В -> Vgs≈0 ->
//      MOSFET ЗАКРИТИЙ. Це і є типовий/безпечний стан.
//    • Т2 керується ШІМ з GPIO: коли він відкривається, Т1 закривається, а
//      затвор тягнеться в мінус -> Vgs сильно від'ємний -> MOSFET ВІДКРИТИЙ.
//      Тобто чим більше часу GPIO проводить у HIGH (вища шпаруватість), тим
//      сильніше відкритий ключ — рівно те, що й дає CHARGE_PWM_INVERT
//      незаданим (типова полярність нижче).
//    • На керуючому вході Т2 — підтяжка до GND (підтверджено власником): при
//      скиданні/завантаженні ESP32, поки GPIO32 висить у високоімпедансному
//      стані, підтяжка гарантує Т2 закритим, Т1 тримає гейт на +14 В,
//      MOSFET закритий. Саме цей апаратний запобіжник обов'язковий — без
//      нього кожне скидання пристрою могло б на мить відкрити ключ на
//      невизначену шпаруватість.
//  ⚠️ Це підтверджено для КОНКРЕТНОЇ описаної власником схеми. Якщо схема
//  зміниться (інші транзистори, інша підтяжка) — перевірте знову мультиметром
//  БЕЗ АКБ: шпаруватість 0 % (стан одразу після chargeInit()) має відповідати
//  відсутності провідності вхід->дросель. Якщо навпаки — CHARGE_PWM_INVERT.
//
//  СТРУМ. Свій датчик не потрібен: той самий струмовимірювальний резистор
//  DS2438 стоїть усередині пакета послідовно з банками, тож і зарядний струм
//  (у протилежному до розряду напрямку) видно у його регістрі струму й у
//  лічильнику CCA.
//
//  Заряд ВИМКНЕНО, доки не задано CHARGE_PIN.
#define CHARGE_PIN 32      // вільний GPIO (не перетинається з жодним іншим
                           // призначенням у цьому проєкті). Закоментуйте рядок,
                           // щоб вимкнути функцію заряду.
// #define CHARGE_PWM_INVERT   // розкоментувати, якщо перевірка показала обернену полярність

// ── СТРУМ: профіль уставки за відсотком заряду (за напругою пакета, шкала
//    BATTERY_EMPTY_MV..BATTERY_FULL_MV = 0..100 %, impresPercentFromMv) ──────
//    0 %      -> CHARGE_MA_START
//    0..10 %  -> лінійно до CHARGE_MA_10
//    10..50 % -> лінійно до CHARGE_MA_50
//    50..80 % -> лінійно до CHARGE_MA_80
//    80..95 % -> тримається на CHARGE_MA_80 (плато; окреме значення для цього
//               відрізка не задавалось — найбезпечніший вибір це не піднімати
