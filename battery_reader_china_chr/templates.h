//  «ЧИСТИЙ» (не навчений) КАЛІБРУВАЛЬНИЙ ХВІСТ 0x18A..0x1FF, 118 байт.
//
//  ⚠️ ЧОМУ ЦЕ ПОТРІБНО, А СТИРАННЯ У 0xFF — НЕ ПРАЦЮЄ.
//  Зарядна станція пише навчені значення за ФІКСОВАНИМИ адресами й НЕ створює
//  структуру записів заново. Прямий доказ — dumps/13-dozaryadka-na-stantsii:
//  у дампі 01 хвіст стерто в 0xFF, після ПОВНОГО циклу на ЗП у дампі 02
//  з'явилися рівно ДВА байти (0x1E1, 0x1E2), а байт довжини 0x1E0 лишився 0xFF.
//  Тобто на стертому хвості навчена калібровка не може стати валідною ніколи:
//  рація АКБ приймає, але калібрування щоразу завершується помилкою.
//
//  Тому ремонт = записати ЧИСТИЙ хвіст: скелет записів (байти довжини) і сталі
//  моделі лишаються, навчені значення обнулені, контрольні суми перераховані.
//
//  Як отримано: побайтове порівняння всіх екземплярів моделі з ЦІЛИМ хвостом.
//  Байт однаковий у всіх -> стала моделі, лишається; байт різниться -> навчене
//  значення, обнуляється. Далі перерахунок сум (Σ запису ≡ 0x5A). Запис-прапорці
//  (3 байти, суми не має) лишається як у genuine-АКБ.
//
//  Правило перевірено перехресно: згенерований «чистий» вигляд записів 0x1A5 і
//  0x1C0 для PMNN4409A/B ТОЧНО збігся з тим, який реально спостерігається у
