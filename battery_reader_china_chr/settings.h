// Піни ESP32
// ⚑ НА ЦЬОМУ ПІНІ СТОЇТЬ РЕЗИСТОР 4.7 кОм НА +3.3 В — але він НЕ обов'язковий.
//  Власник поставив його для попереднього налагодження функцій; прошивка
//  керує цією лінією активно (і вгору, і вниз), тож зовнішня підтяжка тут не
//  умова роботи, а зручність під час перевірок.
//
//  ⚠️ Раніше в цьому файлі стояло «обов'язково, без нього некоректно
//  працюють усі чотири функції». Це було моє припущення, а не факт із цієї
//  плати, — власник його виправив. Різниця не косметична: «обов'язково»
//  відправляє шукати несправність у ненайденому резисторі, якого може й не
//  бути в схемі, і при цьому не бути жодної проблеми.
//
//  ⚠️ НЕ ПЛУТАТИ з підтяжкою ЛІНІЇ ДАНИХ (DS_PIN нижче) — ОТА обов'язкова:
//  чипи DS2433/DS2438 живляться з неї паразитно.
//
//  ⚠️ І ОДРАЗУ ПРО STRAPPING. GPIO12 — це MTDI: рівнем на ньому В МОМЕНТ
//  СКИДАННЯ ESP32 вибирає напругу живлення флеш-пам'яті, і HIGH означає
//  «флеш 1.8 В». На модулях із флешем 3.3 В підтягнутий угору GPIO12
//  зазвичай означає, що плата взагалі не завантажиться.
//  Те, що ЦЕЙ пристрій із припаяним резистором 4.7 кОм завантажується, означає одне з
//  двох: або на модулі вже пропалено eFuse напруги флеша (тоді рівень на
//  GPIO12 при старті просто ігнорується — саме для цього Espressif і дає
//  `espefuse.py set_flash_voltage 3.3V`), або флеш там і справді 1.8 В
//  (WROVER та подібні).
//  Практичний висновок: на ЦІЙ платі резистор стоїть і не заважає, але при
//  переносі на інший модуль перше, що варто перевірити, — чи вона стартує.
//  Якщо не стартує — резистор можна просто зняти: він тут не обов'язковий.
//  Якщо ні — пропалити eFuse або перенести enable на вільний GPIO32
//  (ADC1_CH4, повноцінний вхід/вихід, без strapping-обмежень).
