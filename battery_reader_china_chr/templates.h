//  реального АКБ із нульовим записом 0x18A — тобто «чистий хвіст» однозначно
//  відрізняється від навченого.
//
//  Кількість екземплярів, на яких виведено кожен шаблон, — у коментарі поруч.
//  Для моделей без достатньої вибірки шаблону немає (nullptr): краще чесно
