//  найвище, що треба розрізняти, — аварійна межа (ціль + запас) із запасом
//  зверху. Вище цього показання можуть «залипати» — то вже аварія, і вона
//  однаково спрацює.
#define CHARGE_VSENSE_MAX_READ_MV 9000
// Опорна шкала для перерахунку відліку в мілівольти. Свідомо analogRead() і
// проста пропорція, а НЕ analogReadMilliVolts(): остання спирається на
