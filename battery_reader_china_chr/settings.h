#define CHARGE_TEMP_EVERY_N      10

// ── РЕГУЛЯТОР ШПАРУВАТОСТІ ────────────────────────────────────────────────
// Частота й роздільність ШІМ.
//
// ⚑ 25 кГц — вимога САМОГО ПОНИЖУВАЧА, а не смаку. Розмах пульсацій струму
// ΔI = (Uживл − Uвих) × D / (L × f): на 1 кГц зі 104 мкГн вийшли б десятки
// ампер, тобто глибоко переривчастий режим. На 25 кГц при 14 В -> 8.4 В,
// D≈0.6 і L=104 мкГн це ΔI ≈ 1.30 А — прийнятно на крейсерському струмі
// 1.5 А. Потрібні менші пульсації — піднімайте частоту або індуктивність;
// перевірка наприкінці блока рахує ΔI за ВАШИМИ числами й попереджає.
//
// ⚠️ Знизу частоту обмежує дросель, зверху — ЗАТВОРНЕ КОЛО (τ = R_pullup ×
// Ciss) і роздільність LEDC (макс. частота = 80 МГц / 2^bits). Обидві межі
// перевіряються на компіляції: проєкт уже горів на тому, що 20 кГц
// недосяжні на 12 бітах (80 МГц/4096 = 19.5 кГц). На 11 бітах максимум
// ≈39 кГц, тож 25 кГц проходять із запасом, а 2048 кроків шпаруватості
// дають крок струму ~11 мА (при 14 В і сумарних 0.6 Ом).
#define CHARGE_PWM_FREQ  25000
#define CHARGE_PWM_BITS  11

// ── КРОК РЕГУЛЯТОРА: пропорційний, із двома межами ────────────────────────
//  Один відлік шпаруватості коштує приблизно Uживл/(Rсумарне × 2047) ≈
//  14/(0.6 × 2047) ≈ 11 мА (у неперервному режимі, де I = (D×Uживл −
//  Uпакета)/R). Звідси й перерахунок похибки в кроки.
//
//  ⚑ ЧОМУ КРОК НЕ ФІКСОВАНИЙ. Стартова оцінка шпаруватості спирається на
//  індуктивність і сумарний опір, а обидва відомі приблизно (дросель — «десь
//  104 мкГн», опір пакета взагалі плаває). Фіксований дрібний крок означав би,
//  що будь-яка похибка моделі коштує хвилини повзання: від 200 мА до 1000 мА
//  це ~600 відліків, тобто 5 хвилин при кроці 2. Тому крок пропорційний
//  похибці й затиснутий з обох боків: великий розрив закривається за кілька
//  опитувань, а біля уставки крок стає мінімальним, щоб контур не «сіпався».
//  Так контур лишається стійким навіть якщо CHARGE_L_UH задано неточно.
#define CHARGE_DUTY_MA_PER_STEP  11   // скільки мА коштує один відлік ШІМ
#define CHARGE_DUTY_STEP          2   // мінімальний крок (точне доведення)
#define CHARGE_DUTY_STEP_MAX     64   // стеля кроку (швидкий вихід на режим)

// Сумарний послідовний опір кола заряду, мОм: шунт + дроти + внутрішній опір
// пакета. Потрібен лише для СТАРТОВОЇ оцінки шпаруватості у неперервному
// режимі; далі все веде замкнутий контур за реальним струмом, тож похибка тут
// не критична. Шунт (CHARGE_SHUNT_MOHM) домінує, решта — оцінка.
#define CHARGE_SERIES_MOHM      600

// Стеля шпаруватості, % — ключ НІКОЛИ не відкривається повністю.
//
// ⚑ Для понижувача це ще й обмеження ВИХІДНОЇ НАПРУГИ: Uвих ≈ D × Uживл.
// Рахуємо потрібний мінімум: ціль 8.25 В + падіння на шунті (0.5 Ом × 1.5 А
// = 0.75 В) + діод/дросель/дроти/ключ (~0.5 В) ≈ 9.5 В, тобто D ≈ 9.5/14 ≈
// 0.68. Беремо 85 % — є запас на просілий блок живлення й на гірший випадок
// за струмом, але 100 % не досягається ніколи: на повністю відкритому ключі
// понижувач вироджується у пряме з'єднання живлення з пакетом.
// ⚠️ Ставите ІНШЕ живлення — перерахуйте: замала стеля означає, що заряд не
// дотягне до цілі й упреться в стелю часу.
#define CHARGE_DUTY_MAX_PCT  85

// Мертва зона навколо уставки, мА — щоб контур не «сіпав» шпаруватість на
// шумі вимірювання ±1 крок туди-сюди.
#define CHARGE_DEADBAND_MA   30

// АВАРІЙНА відсічка за ПІКОВИМ струмом, мА (найбільший відлік за час виміру).
//
// ⚑ У понижувача пік — це ВЕРШИНА ПУЛЬСАЦІЙ (Iсер + ΔI/2), а не кидок:
// дросель не дає струму стрибнути. Тож ця відсічка стереже НЕ штатну роботу,
// а поломки, за яких дроселя фактично немає в колі: обрив або насичення
// дроселя, пробитий ключ, замкнений діод. Поріг мусить бути помітно вищим за
// (найбільша уставка + півпульсації), інакше ловитиме штатний режим.
#define CHARGE_PEAK_MA_MAX   3000

// ── «КЛЮЧ НЕ ТЯГНЕ»: відсічка за НЕДОСТАТНІМ струмом на стелі шпаруватості ──
//  Дзеркало пікової відсічки, і потрібна вона рівно з тієї ж причини —
//  вберегти силовий ключ. Якщо шпаруватість уперлась у стелю, а струм усе одно
//  помітно нижчий за уставку, це означає, що коло не здатне віддати
//  замовлений струм. Найнебезпечніша з причин — ключ ПОЗА НАСИЧЕННЯМ (замалий
//  струм бази: саме такий стан дає плата з нинішніми 1 кОм і 20 кОм в обв'язці,
//  див. CHARGE_BASE_DRIVE_OHM / CHARGE_NPN_BASE_OHM). Транзистор при цьому
//  працює в лінійному режимі під повною напругою живлення й гріється так, як
//  жоден із теплових розрахунків вище не передбачає.
//  Реакція регулятора на «мало струму» — піднімати шпаруватість, тобто саме те,
//  що погіршує становище. Тому потрібна окрема відсічка, а не сподівання на
//  стелю часу: та спрацює через шість годин, коли палити вже нічого.
//  Інші причини того ж симптому — обрив дроселя, поганий контакт, просілий блок
//  живлення — теж заслуговують на зупинку, а не на шість годин удавання роботи.
#define CHARGE_NODRIVE_PCT    50    // «помітно нижчий» = менше половини уставки
#define CHARGE_NODRIVE_POLLS  5     // стільки опитувань поспіль (CHARGE_POLL_MS кожне)
// Скільки опитувань поспіль подільник мусить стояти в стелі, щоб оголосити
// «пакет від'єднано». Два — бо chargePackMv() не усереднює (один analogRead),
// а тримати заряд довше немає сенсу: пакета в колі вже немає.
#define CHARGE_NOPACK_POLLS   2

// ── ПАКЕТ ЗАКРИВАЄТЬСЯ САМ, ДІЙШОВШИ ДО СВОЄЇ МЕЖІ ────────────────────────
//  Спостереження власника: на 8.2 В пакет розмикає власний захист. Клема при
//  цьому лишається без навантаження, подільник іде в стелю — і зовні це
//  виглядає точно так само, як загублений контакт. Формально однаково, по суті
//  протилежне: у першому випадку заряд ЗАВЕРШЕНО, у другому — АВАРІЯ.
//
//  Розрізняє їх монітор DS2438: він сидить УСЕРЕДИНІ пакета, живиться від
//  банок і має власну лінію даних, тож розмикання силового ключа пакета його
//  не глушить. Витягнули пакет — монітор мовчить. Пакет на місці, але закрив
//  себе сам — монітор відповідає й називає справжню напругу банок.
//
