//  струму, за якого ключ вигорить.
#define CHARGE_BJT_IC_MAX_MA    3000   // Ic max, мА (B772M: 3 А)
#define CHARGE_BJT_PC_MW        1250   // Pc max, мВт (B772M: 1.25 Вт)
// Напруга насичення колектор-емітер при робочому струмі, мВ. Саме вона, а не
// опір каналу, дає провідні втрати: P = Uке_нас × Iк × D.
#define CHARGE_BJT_VCE_SAT_MV   500
// Форсований коефіцієнт передачі: у скільки разів струм колектора більший за
// струм бази. Для НАДІЙНОГО насичення беруть 10…20 (а не паспортний hFE:
// той міряють у лінійному режимі й на межі насичення він не тримається).
#define CHARGE_BJT_HFE_FORCED   20
// Сумарний час перемикання (розсмоктування заряду бази + спад), нс.
//  ⚠️ Це головна відмінність від MOSFET. Біполярник у насиченні накопичує
//  заряд у базі, і з РЕЗИСТИВНИМ вимиканням розсмоктування триває
//  мікросекунди. 3000 нс — обережна оцінка для B772M без активного
//  запирання; із запираючим резистором база-емітер буде менше.
#define CHARGE_BJT_TSW_NS       3000

// Резистор, що ЗАДАЄ СТРУМ БАЗИ силового ключа (між колектором NPN і базою
// PNP), Ом. Насичення мусить триматись на ВЕРШИНІ ПУЛЬСАЦІЙ, а не на
// середньому струмі, інакше ключ виходить із насичення на кожному горбі.
//
// ⚠️⚠️ НА ПЛАТІ ЗАРАЗ СТОЇТЬ 1 кОм — ЦЕ ТРЕБА ЗАМІНИТИ НА 150 Ом.
//  Причина не в запасі, а в тому, що з 1 кОм заряд фізично не працює:
//    Iб = (14 − 0.9 − 0.2)/1000 − витік у підтяжку 0.9 мА = 12 мА.
//  При β_форс 20 це стеля колектора 240 мА, а з урахуванням пульсацій
//  дроселя (пік удвічі-втричі вищий за середнє) СЕРЕДНІЙ струм заряду вийшов
//  би ~22 мА. Пакет 2150 мА·год заряджався б ЧОТИРИ ДОБИ. А якщо всупереч
//  цьому виставити більший струм — ключ не насититься, лишиться в лінійному
//  режимі й згорить за секунди.
//  Із 150 Ом: Iб = 85 мА, чого вистачає на пік 1651 мА (β_форс 19).
//  Перевірка наприкінці блока не дасть зібрати прошивку, доки номінал не
//  відповідає обраному профілю струму.
#define CHARGE_BASE_DRIVE_OHM   150
//  ⚠️ Розсіює Iб²×R×D — при 86 мА це ~0.65 Вт, тож резистор брати 1…2 Вт.
//  І NPN мусить пропускати ці 86 мА: BC547 (100 мА max) впритул, потрібен
//  2N2222 / BC337 / S8050.

// Падіння на переході база-емітер PNP і на насиченому NPN, мВ — для розрахунку
// струму бази.
#define CHARGE_BJT_VBE_MV       900
#define CHARGE_NPN_VCE_SAT_MV   200

// Запираючий резистор база-емітер PNP, Ом — тримає ключ закритим у спокої й
// прискорює розсмоктування заряду бази при вимиканні.
//  ⚑ Він же ВІДБИРАЄ частину струму драйвера: поки ключ відкритий, через
//  нього тече Uбе/R_підт (при 1 кОм — 0.9 мА), і ці міліампери до бази вже не
//  доходять. На 1 кОм це 1 % від 86 мА — дрібниця, але у формулі струму бази
//  нижче враховано, бо на дрібнішій підтяжці витік став би відчутним.
#define CHARGE_BASE_PULLUP_OHM  1000

// ── ДРАЙВЕРНИЙ КАСКАД: керуючий NPN між піном і базою силового PNP ────────
//  Резистор від піна до бази NPN. ⚠️ 470 Ом, а не «десь кілоом»: через
//  колектор NPN тече ВЕСЬ струм драйвера (86 мА), і при 1 кОм струм його
