#define CHARGE_HARD_MAX_HEADROOM_MV 100

// Відсічка за температурою пакета (DS2438), °C.
#define CHARGE_MAX_TEMP_C   45

// Період опитування, мс.
#define CHARGE_POLL_MS       1000UL

// Скільки тримати ключ ЗАКРИТИМ перед виміром напруги пакета, мс.
//
//  Напруга на клемі й так згладжена дроселем (на відміну від простого ключа,
//  де там стрибала б напруга живлення), але ПІД СТРУМОМ до неї додається
