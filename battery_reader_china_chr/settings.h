#define CHARGE_SUPPLY_MV        14000

// ── СИЛОВІ КОМПОНЕНТИ ПОНИЖУВАЧА ──────────────────────────────────────────
// Індуктивність дроселя, мкГн. Визначає розмах пульсацій струму:
//   ΔI = (Uживл − Uвих) × D / (L × f).
// Якщо точне значення невідоме — візьміть із маркування; від нього залежить
// перевірка «чи не завеликі пульсації» наприкінці блока.
#define CHARGE_L_UH             104

// ── СИЛОВИЙ КЛЮЧ: біполярний PNP (за замовчуванням B772M) ─────────────────
//  Паспортні межі — з даташита. Вони НЕ довідкові: за ними рахуються
