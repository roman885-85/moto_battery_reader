#define CHARGE_ADC_SAMPLES      128

// ── СТРУМ: профіль уставки за відсотком заряду (за напругою пакета, шкала
//    BATTERY_EMPTY_MV..BATTERY_FULL_MV = 0..100 %, impresPercentFromMv) ──────
//    Точки перегину задані для ЦІЛІ 100 %. Якщо користувач обирає ЦІЛЬ НИЖЧУ
//    (див. CHARGE_TARGET_PRESETS_PCT у charge.h) — ВСІ точки масштабуються
//    пропорційно (chargeSetpointMaForPct), тож форма профілю (розгін ->
