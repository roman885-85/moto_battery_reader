#define DISCHARGE_MAX_READ_FAILS 3

// ── СТОРОЖОВИЙ ТАЙМЕР РОЗРЯДУ ──────────────────────────────────────────────
//  Розряд — єдиний режим, де пристрій тримає замкнутим силовий ключ І сигнал
//  enable без участі людини. Якщо головний цикл зависне (збій Wi-Fi-стека,
//  нескінченне очікування на шині, будь-що), ключ так і лишиться відкритим, а
//  пакет саджатиметься в нуль. Тому на час розряду вмикається сторож:
//
