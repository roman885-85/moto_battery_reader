    #error "CHARGE_PWM_PIN / CHARGE_ISENSE_PIN / CHARGE_VSENSE_PIN мають бути РІЗНИМИ пінами."
  #endif

  // --- ШІМ-вихід ---
  #if (CHARGE_PWM_PIN == DS_PIN) || (CHARGE_PWM_PIN == PULLUP_PIN) || \
      (CHARGE_PWM_PIN == LED_GREEN_PIN) || (CHARGE_PWM_PIN == LED_RED_PIN) || \
      (defined(MENU_BTN_PIN) && CHARGE_PWM_PIN == MENU_BTN_PIN) || \
      (defined(MENU_BTN2_PIN) && CHARGE_PWM_PIN == MENU_BTN2_PIN) || \
      (defined(MENU_BTN3_PIN) && CHARGE_PWM_PIN == MENU_BTN3_PIN) || \
      (defined(MENU_BTN_ADC_PIN) && CHARGE_PWM_PIN == MENU_BTN_ADC_PIN) || \
      (defined(BUZZER_PIN) && CHARGE_PWM_PIN == BUZZER_PIN) || \
      (defined(BUZZER_DAC_PIN) && CHARGE_PWM_PIN == BUZZER_DAC_PIN) || \
      (defined(BTN_LED_PIN) && CHARGE_PWM_PIN == BTN_LED_PIN) || \
      (defined(LOAD_PIN) && CHARGE_PWM_PIN == LOAD_PIN) || \
      (CHARGE_PWM_PIN == DISPLAY_SDA_PIN) || (CHARGE_PWM_PIN == DISPLAY_SCL_PIN) || \
      (defined(DISPLAY_CS_PIN) && CHARGE_PWM_PIN == DISPLAY_CS_PIN) || (CHARGE_PWM_PIN == DISPLAY_DC_PIN)  || \
      (CHARGE_PWM_PIN == DISPLAY_RST_PIN) || \
      (defined(DISPLAY_BLK_PIN) && CHARGE_PWM_PIN == DISPLAY_BLK_PIN)
    #error "CHARGE_PWM_PIN конфліктує з уже зайнятим піном! Оберіть вільний вихідний GPIO."
  #endif
  #if (CHARGE_PWM_PIN >= 34)
    #error "CHARGE_PWM_PIN на GPIO34..39 неможливий: ці піни ВХІД-ТІЛЬКИ, а тут потрібен ШІМ-вихід."
  #endif
  #if (CHARGE_PWM_PIN == 0)
    #error "CHARGE_PWM_PIN на GPIO0 неможливий: strapping-пін, підтяжка бази не дала б завантажитись."
  #endif

  // --- вимірювальні входи: ЛИШЕ ADC1 ---
  //  ADC2 (0,2,4,12-15,25-27) не працює при активному Wi-Fi, а точка доступу
  //  в цьому проєкті піднята завжди — вимірювання заряду просто не читалися б.
  #if (CHARGE_ISENSE_PIN < 32) || (CHARGE_ISENSE_PIN > 39)
    #error "CHARGE_ISENSE_PIN має бути входом ADC1 (GPIO32..39): ADC2 не читається при увімкненому Wi-Fi."
  #endif
  #if (CHARGE_VSENSE_PIN < 32) || (CHARGE_VSENSE_PIN > 39)
    #error "CHARGE_VSENSE_PIN має бути входом ADC1 (GPIO32..39): ADC2 не читається при увімкненому Wi-Fi."
  #endif
  #if (defined(MENU_BTN_ADC_PIN) && CHARGE_ISENSE_PIN == MENU_BTN_ADC_PIN) || \
      (defined(MENU_BTN_ADC_PIN) && CHARGE_VSENSE_PIN == MENU_BTN_ADC_PIN)
    #error "Вимірювальний пін заряду збігається з ADC-драбинкою кнопок (MENU_BTN_ADC_PIN)."
  #endif

  // --- подільник: (1) ДІАПАЗОН ВИМІРУ і (2) СТРУМ У ЗАХИСНИЙ ДІОД ---
  //
  //  Раніше тут була ОДНА перевірка — «напруга живлення через подільник не
  //  вище робочої межі АЦП». Вона надто груба: у штатній роботі на клемі
  //  стоїть напруга ПАКЕТА, а живлення там опиняється лише у нештатному
  //  випадку (пакет від'єднали посеред заряду). Вимагати запасу під нештатний
  //  випадок означає без потреби гробити роздільність у штатному — саме через
  //  це й народилась хибна порада «поставте 2.7к знизу».
  //  Тому дві окремі умови, кожна про своє.

  //  (1) ДІАПАЗОН: усе, що прошивка мусить розрізняти, має лягати в робочу
  //  стелю АЦП. Вище цього показання «залипають» — але то вже аварія.
  #if ((CHARGE_VSENSE_MAX_READ_MV) * (CHARGE_VSENSE_R_BOT) / \
       ((CHARGE_VSENSE_R_TOP) + (CHARGE_VSENSE_R_BOT))) > (CHARGE_ADC_MAX_MV)
    #error "Подільник CHARGE_VSENSE_R_TOP/R_BOT виводить робочий діапазон за стелю АЦП: прошивка не побачить аварійну напругу. Збільште верхнє плече або зменште нижнє."
  #endif

  //  (2) ЗАХИСНИЙ ДІОД: у нештатному випадку (пакет від'єднано, на клемі
  //  напруга живлення) вузол подільника хоче піднятись вище абсолютної межі
  //  входу. Пін це переживає, ПОКИ струм у діод малий, а обмежує його власний
  //  опір подільника (Rверх∥Rниз) плюс послідовний резистор.
  //  Від'ємне значення (клампу немає взагалі) умову не порушує.
  #define CHARGE_VSENSE_NODE_AT_SUPPLY_MV \
      ((CHARGE_SUPPLY_MV) * (CHARGE_VSENSE_R_BOT) / \
       ((CHARGE_VSENSE_R_TOP) + (CHARGE_VSENSE_R_BOT)))
  #define CHARGE_VSENSE_SRC_OHM \
      ((CHARGE_VSENSE_R_TOP) * (CHARGE_VSENSE_R_BOT) / \
       ((CHARGE_VSENSE_R_TOP) + (CHARGE_VSENSE_R_BOT)) + (CHARGE_VSENSE_R_SERIES))
  #define CHARGE_VSENSE_CLAMP_UA \
      (((CHARGE_VSENSE_NODE_AT_SUPPLY_MV) - (CHARGE_ADC_ABS_MAX_MV)) * 1000 / \
       (CHARGE_VSENSE_SRC_OHM))
  #if (CHARGE_VSENSE_CLAMP_UA) > (CHARGE_ADC_CLAMP_UA_MAX)
    #error "Якщо пакет від'єднати посеред заряду, на клемі лишиться напруга живлення, і струм у захисний діод входу перевищить безпечний. Підніміть номінали подільника (більший власний опір) або CHARGE_VSENSE_R_SERIES."
  #endif

  //  (2а) ТА САМА АВАРІЯ, АЛЕ З БОКУ ПРОШИВКИ. Перевірка (2) стежить, щоб пін
  //  ЦЕ ПЕРЕЖИВ; ця — щоб прошивка правильно НАЗВАЛА побачене. Поріг
  //  CHARGE_VSENSE_SAT_MV відділяє «пакет під напругою» від «на клемі
  //  живлення» (chargeSenseSaturated() у charge.h). Він мусить лежати САМЕ
  //  МІЖ двома числами, інакше відсічка або краде чужі випадки, або мертва:
  //
  //    аварійна межа  <  поріг насичення  <  найбільше можливе показання
  //       8350 мВ     <      9300 мВ      <         9900 мВ
  //
  //  Ліва межа: нижче за неї відсічка з'їдала б справжню перенапругу й
  //  називала б її «пакет від'єднано».
  #if (CHARGE_VSENSE_SAT_MV) <= ((CHARGE_TARGET_MV) + (CHARGE_HARD_MAX_HEADROOM_MV))
    #error "Поріг насичення подільника (CHARGE_ADC_MAX_MV × подільник) не вищий за аварійну межу напруги: справжня перенапруга буде показана як «пакет від'єднано». Підніміть верхнє плече подільника або знизьте CHARGE_HARD_MAX_HEADROOM_MV."
  #endif
  //  Права межа: chargePackMv() фізично не може видати більше за
  //  CHARGE_VSENSE_RAIL_MV (відлік 4095). Якщо поріг доріс до цього числа,
  //  умова mv >= поріг не справдиться НІКОЛИ — відсічка тихо помре, а скарга
  //  «9.9 В, перенапруга» повернеться. Саме такі мовчазні відмови цей файл і
  //  ловить.
  #if (CHARGE_VSENSE_SAT_MV) >= (CHARGE_VSENSE_RAIL_MV)
    #error "Поріг насичення дорівнює найбільшому можливому показанню або вищий за нього — відсічка «пакет від'єднано» не спрацює НІКОЛИ. CHARGE_ADC_MAX_MV мусить бути меншим за CHARGE_ADC_FULL_MV."
  #endif

  //  (3) САМОРОЗРЯД ЧЕРЕЗ ПОДІЛЬНИК. Він висить на плюсовій клемі ПОСТІЙНО,
  //  доки пакет під'єднано, — і тихо його розряджає. При 20к+10к це
  //  8.25 В / 30 кОм ≈ 275 мкА, тобто ~0.2 А·год за місяць: помітно, але
  //  прийнятно. А от подільник на кілоомах давав би вже міліампери й садив
  //  пакет за тижні — при тому, що виміру це не покращує ніяк.
  #define CHARGE_VSENSE_DRAIN_UA \
      ((CHARGE_TARGET_MV) * 1000 / ((CHARGE_VSENSE_R_TOP) + (CHARGE_VSENSE_R_BOT)))
  #ifndef CHARGE_VSENSE_DRAIN_UA_MAX
    #define CHARGE_VSENSE_DRAIN_UA_MAX 500
  #endif
  #if (CHARGE_VSENSE_DRAIN_UA) > (CHARGE_VSENSE_DRAIN_UA_MAX)
    #error "Подільник напруги надто низькоомний: він постійно висить на пакеті й саджає його. Підніміть номінали (зберігши співвідношення)."
  #endif

  // --- СПАДКОВИЙ ПІН ПОПЕРЕДНЬОЇ СХЕМИ ЗАРЯДУ ---
  #ifdef CHARGE_LEGACY_EN_PIN
    #if (CHARGE_LEGACY_EN_PIN == CHARGE_PWM_PIN) || \
        (CHARGE_LEGACY_EN_PIN == CHARGE_ISENSE_PIN) || \
        (CHARGE_LEGACY_EN_PIN == CHARGE_VSENSE_PIN) || \
        (defined(CHARGE_PSU_PIN) && CHARGE_LEGACY_EN_PIN == CHARGE_PSU_PIN) || \
        (CHARGE_LEGACY_EN_PIN == DS_PIN) || (CHARGE_LEGACY_EN_PIN == PULLUP_PIN) || \
        (CHARGE_LEGACY_EN_PIN == LED_GREEN_PIN) || (CHARGE_LEGACY_EN_PIN == LED_RED_PIN) || \
        (defined(LOAD_PIN) && CHARGE_LEGACY_EN_PIN == LOAD_PIN) || \
        (defined(BTN_LED_PIN) && CHARGE_LEGACY_EN_PIN == BTN_LED_PIN) || \
        (defined(MENU_BTN_ADC_PIN) && CHARGE_LEGACY_EN_PIN == MENU_BTN_ADC_PIN) || \
        (defined(DISPLAY_BLK_PIN) && CHARGE_LEGACY_EN_PIN == DISPLAY_BLK_PIN) || \
        (CHARGE_LEGACY_EN_PIN == DISPLAY_DC_PIN) || (CHARGE_LEGACY_EN_PIN == DISPLAY_RST_PIN)
      #error "CHARGE_LEGACY_EN_PIN збігається з піном, який використовується. Це пін СТАРОЇ схеми заряду — якщо доріжку зрізано, просто закоментуйте його."
    #endif
    #if (CHARGE_LEGACY_EN_PIN >= 34)
      #error "CHARGE_LEGACY_EN_PIN на GPIO34..39 неможливий: ці піни ВХІД-ТІЛЬКИ, а його треба утримувати в LOW."
    #endif
  #endif

  // --- КОНТРОЛЬ ЖИВЛЕННЯ: пін і подільник ---
  #ifdef CHARGE_PSU_PIN
    #if (CHARGE_PSU_PIN < 32) || (CHARGE_PSU_PIN > 39)
      #error "CHARGE_PSU_PIN має бути входом ADC1 (GPIO32..39): ADC2 не читається при увімкненому Wi-Fi."
    #endif
    #if (CHARGE_PSU_PIN == CHARGE_ISENSE_PIN) || (CHARGE_PSU_PIN == CHARGE_VSENSE_PIN) || \
        (CHARGE_PSU_PIN == CHARGE_PWM_PIN) || \
        (defined(MENU_BTN_ADC_PIN) && CHARGE_PSU_PIN == MENU_BTN_ADC_PIN)
      #error "CHARGE_PSU_PIN збігається з уже зайнятим піном (вимір заряду або драбинка кнопок)."
    #endif
    //  Той самий двоскладовий критерій, що й для подільника клеми: спершу
    //  ДІАПАЗОН (усе, що треба розрізняти, лягає в робочу стелю АЦП)...
    #if ((CHARGE_PSU_MAX_READ_MV) * (CHARGE_PSU_R_BOT) / \
         ((CHARGE_PSU_R_TOP) + (CHARGE_PSU_R_BOT))) > (CHARGE_ADC_MAX_MV)
      #error "Подільник CHARGE_PSU_R_TOP/R_BOT виводить робочий діапазон за стелю АЦП: помилковий блок живлення читався б як «залипле» 4095. Збільште верхнє плече."
    #endif
    //  ...потім СТРУМ У ЗАХИСНИЙ ДІОД при явно завищеному живленні. Беремо
    //  подвійну номінальну напругу — це вже не «інший блок», а помилка
    //  підключення, і пін мусить її пережити.
    #define CHARGE_PSU_SRC_OHM \
        ((CHARGE_PSU_R_TOP) * (CHARGE_PSU_R_BOT) / \
         ((CHARGE_PSU_R_TOP) + (CHARGE_PSU_R_BOT)) + (CHARGE_PSU_R_SERIES))
    #define CHARGE_PSU_CLAMP_UA \
        ((((CHARGE_SUPPLY_MV) * 2 * (CHARGE_PSU_R_BOT) / \
           ((CHARGE_PSU_R_TOP) + (CHARGE_PSU_R_BOT))) - (CHARGE_ADC_ABS_MAX_MV)) * 1000 / \
         (CHARGE_PSU_SRC_OHM))
    #if (CHARGE_PSU_CLAMP_UA) > (CHARGE_ADC_CLAMP_UA_MAX)
      #error "При вдвічі завищеному живленні струм у захисний діод CHARGE_PSU_PIN перевищує безпечний. Підніміть номінали подільника живлення або CHARGE_PSU_R_SERIES."
    #endif

    // --- пороги мусять іти по порядку й охоплювати номінал ---
    #if (CHARGE_PSU_ABSENT_MV) >= (CHARGE_PSU_MIN_MV)
      #error "CHARGE_PSU_ABSENT_MV має бути НИЖЧЕ за CHARGE_PSU_MIN_MV: «немає живлення» — це окремий випадок «занизької напруги», а не той самий поріг."
    #endif
    #if (CHARGE_PSU_MIN_MV) >= (CHARGE_PSU_MAX_MV)
      #error "CHARGE_PSU_MIN_MV не нижче за CHARGE_PSU_MAX_MV — робочого діапазону живлення не лишилось."
    #endif
    #if ((CHARGE_SUPPLY_MV) < (CHARGE_PSU_MIN_MV)) || ((CHARGE_SUPPLY_MV) > (CHARGE_PSU_MAX_MV))
      #error "Номінальне CHARGE_SUPPLY_MV лежить ПОЗА власним робочим діапазоном CHARGE_PSU_MIN_MV..CHARGE_PSU_MAX_MV — прошивка відхиляла б штатний блок живлення."
    #endif
#if CHARGE_SW_IS_BJT
    //  Найнижче ДОПУСТИМЕ живлення мусить лишати ключ у насиченні: струм бази
    //  падає разом із напругою живлення, а пік струму від неї майже не
    //  залежить. Інакше «блок у межах допуску» все одно означав би лінійний
    //  режим і згорілий ключ.
    #define CHARGE_IB_AT_MIN_PSU_MA \
        (((((CHARGE_PSU_MIN_MV) - (CHARGE_BJT_VBE_MV) - (CHARGE_NPN_VCE_SAT_MV)) * 1000 / \
           (CHARGE_BASE_DRIVE_OHM)) - (CHARGE_BASE_BLEED_UA)) / 1000)
    #if (CHARGE_IB_AT_MIN_PSU_MA) < ((CHARGE_IPEAK_MA) / (CHARGE_BJT_HFE_FORCED))
      #error "На НИЖНІЙ межі допуску живлення (CHARGE_PSU_MIN_MV) струму бази вже не вистачає на насичення ключа. Або підніміть поріг, або зменште CHARGE_BASE_DRIVE_OHM."
    #endif
    //  Для КЕРУЮЧОГО NPN найгірший випадок — ДЗЕРКАЛЬНИЙ, верхня межа: чим
    //  вище живлення, тим більший струм драйвера мусить пропустити його
    //  колектор. Перевіряти лише номінал тут мало: 470 Ом проходили на 14 В і
    //  провалювались на 16 В, залишаючи ключ поза насиченням саме тоді, коли
    //  на ньому й так найбільша напруга.
    #define CHARGE_DRIVE_AT_MAX_PSU_UA \
        (((CHARGE_PSU_MAX_MV) - (CHARGE_BJT_VBE_MV) - (CHARGE_NPN_VCE_SAT_MV)) * 1000 / \
         (CHARGE_BASE_DRIVE_OHM))
    #if (CHARGE_NPN_IB_UA) < ((CHARGE_DRIVE_AT_MAX_PSU_UA) / (CHARGE_NPN_HFE_FORCED))
      #error "На ВЕРХНІЙ межі допуску живлення (CHARGE_PSU_MAX_MV) керуючий NPN уже не насичується: струм драйвера росте з напругою. Зменште CHARGE_NPN_BASE_OHM або опустіть CHARGE_PSU_MAX_MV."
    #endif
    //  І цей більший струм мусить лишатись у межах Ic керуючого NPN.
    #if (CHARGE_DRIVE_AT_MAX_PSU_UA) > (CHARGE_NPN_IC_MAX_MA) * 1000
      #error "На верхній межі живлення струм через керуючий NPN перевищує його Ic max. Поставте потужніший NPN (2N2222/BC337/S8050) і підправте CHARGE_NPN_IC_MAX_MA."
    #endif
#else
    //  ⚑ ДЛЯ ПОЛЬОВОГО ОБИДВІ МЕЖІ ДОПУСКУ ВЖЕ ПЕРЕВІРЕНО ВИЩЕ, і перевірено
    //  саме тими величинами, які тут вирішують справу: CHARGE_MOS_VGS_AT_MIN_PSU_MV
    //  (чи відкриється на просілому блоці) і CHARGE_MOS_VGS_AT_MAX_PSU_MV (чи
    //  не проб'є затвор на завищеному). Дублювати їх тут означало б мати два
    //  місця, які легко розійдуться. Лишається те, чого там немає: провідні
    //  втрати на НИЖНЬОМУ живленні найбільші — шпаруватість вища, ключ
    //  довше відкритий, а I²R від напруги не залежить.
    #define CHARGE_MOS_DUTY_AT_MIN_PSU_PCT \
        ((CHARGE_TARGET_MV) * 100 / (CHARGE_PSU_MIN_MV))
    #define CHARGE_MOS_P_COND_MIN_PSU_MW \
        ((CHARGE_MA_80) * 1LL * (CHARGE_MA_80) * (CHARGE_MOS_RDSON_MOHM) / 1000000LL * \
         (CHARGE_MOS_DUTY_AT_MIN_PSU_PCT) / 100)
    #if ((CHARGE_MOS_P_COND_MIN_PSU_MW) + (CHARGE_P_SW_MW)) > ((CHARGE_SW_PD_MW) * 4 / 5)
      #error "На НИЖНІЙ межі допуску живлення шпаруватість вища, і провідні втрати I²R виводять розсіювання за 80 % паспортної потужності MOSFET."
    #endif
#endif
  #endif  // CHARGE_PSU_PIN

  // --- шунт мусить лишати робочий струм у діапазоні АЦП ---
  #if ((CHARGE_PEAK_MA_MAX) * (CHARGE_SHUNT_MOHM) / 1000) > (CHARGE_ADC_MAX_MV)
    #error "CHARGE_PEAK_MA_MAX на шунті CHARGE_SHUNT_MOHM дає напругу вище робочої межі АЦП — пік просто не буде видно. Зменште шунт або відсічку."
  #endif
  #if (CHARGE_MA_80 >= CHARGE_PEAK_MA_MAX)
    #error "Найбільша уставка струму (CHARGE_MA_80) не нижча за аварійну відсічку CHARGE_PEAK_MA_MAX — заряд аварійно спинявся б на штатному режимі."
  #endif

  // --- межі регулятора ---
  #if (CHARGE_DUTY_MAX_PCT < 1) || (CHARGE_DUTY_MAX_PCT > 100)
    #error "CHARGE_DUTY_MAX_PCT поза межами 1..100."
  #endif
  #if (CHARGE_DUTY_STEP < 1) || (CHARGE_DUTY_STEP > 64)
    #error "CHARGE_DUTY_STEP поза розумними межами (1..64 відліків ШІМ)."
  #endif
  #if (CHARGE_DUTY_STEP_MAX) < (CHARGE_DUTY_STEP)
    #error "CHARGE_DUTY_STEP_MAX не може бути меншим за CHARGE_DUTY_STEP."
  #endif
  #if (CHARGE_DUTY_MA_PER_STEP) < 1
    #error "CHARGE_DUTY_MA_PER_STEP має бути додатним — на нього ділиться похибка струму."
  #endif
  #if (CHARGE_SERIES_MOHM) < (CHARGE_SHUNT_MOHM)
    #error "CHARGE_SERIES_MOHM не може бути меншим за сам шунт (CHARGE_SHUNT_MOHM)."
  #endif

  // --- КАНАЛИ LEDC НЕ МОЖУТЬ ДІЛИТИ ТАЙМЕР ІЗ РІЗНИМИ НАЛАШТУВАННЯМИ ---
  //  Канали діляться таймерами попарно: 0-1 → таймер 0, 2-3 → 1, 4-5 → 2,
  //  6-7 → 3. Таймер має ОДНУ частоту й ОДНУ розрядність, тож два канали на
  //  ньому мусять або збігатися в налаштуваннях, або не співіснувати.
  //  Провал тут МОВЧАЗНИЙ у найгіршому сенсі: ledcAttachChannel() просто
  //  повертає false, прошивка збирається, а заряд відмовляється стартувати з
  //  повідомленням про «канал не знайшовся» — і шукати причину йдуть у залізо.
  //  Саме це й сталось із парою 6/7 (розряд і заряд).
  #if defined(LOAD_PIN) && ((CHARGE_LEDC_CH) / 2 == (LOAD_LEDC_CH) / 2) && \
      ((CHARGE_PWM_FREQ) != (DISCHARGE_PWM_FREQ) || (CHARGE_PWM_BITS) != (DISCHARGE_PWM_BITS))
    #error "CHARGE_LEDC_CH і LOAD_LEDC_CH сидять на ОДНОМУ таймері LEDC (канали діляться попарно: 0-1, 2-3, 4-5, 6-7), а частота/розрядність у них різні. Один із каналів не прикріпиться, і відповідний ключ лишиться некерованим. Оберіть канал з іншої пари."
  #endif
  //  Лише ШІМ-зумер: DAC-варіант (BUZZER_DAC_PIN) грає через ЦАП і таймерне
  //  переривання, LEDC він не займає взагалі.
  #if defined(BUZZER_PIN) && ((CHARGE_LEDC_CH) / 2 == (BUZZER_LEDC_CH) / 2)
    #error "CHARGE_LEDC_CH ділить таймер LEDC із буззером (BUZZER_LEDC_CH). Зумер міняє частоту на кожній ноті — це зіб'є частоту ШІМ заряду. Оберіть канал з іншої пари."
  #endif
  #if (CHARGE_LEDC_CH) < 0 || (CHARGE_LEDC_CH) > 7
    #error "CHARGE_LEDC_CH поза межами 0..7 (низькошвидкісна група LEDC на ESP32)."
  #endif

  // --- ШІМ мусить бути ДОСЯЖНИМ для LEDC ---
  //  Дільник LEDC не може бути меншим за 1, тож максимальна частота на
  //  N-бітному таймері = 80 МГц / 2^N. Проєкт уже горів на цьому: 20 кГц на
  //  12 бітах (макс. 19.5 кГц) мовчки провалювали attach(), і заряд ставав
  //  некерованим. Ловимо на компіляції, а не в логах.
  #if (CHARGE_PWM_FREQ) > (80000000L >> (CHARGE_PWM_BITS))
    #error "CHARGE_PWM_FREQ недосяжна для CHARGE_PWM_BITS: максимум = 80 МГц / 2^bits. Знизьте частоту або розрядність."
  #endif

  // --- СТРУМУ БАЗИ мусить вистачати на НАСИЧЕННЯ ---
  //  Біполярник керується струмом: Iб = (Uживл − Uбе − Uке_нас_npn)/R_бази,
  //  і треба Iб >= Iк/β_форс. Недостатній струм бази означає, що ключ працює
  //  НЕ в насиченні: Uке лишається вольтами, і транзистор згорає за секунди.
  //  Найгірший струм — вершина пульсацій (уставка + ΔI/2), її й беремо.
#if CHARGE_SW_IS_BJT
  #if (CHARGE_IB_MA) < ((CHARGE_IPEAK_MA) / (CHARGE_BJT_HFE_FORCED))
    #error "Струму бази не вистачає на насичення ключа при піковому струмі: зменште CHARGE_BASE_DRIVE_OHM або знизьте CHARGE_MA_80. Ключ поза насиченням згорає за секунди."
  #endif
#else
  // --- ПОЛЬОВИЙ: ЗАМІСТЬ СТРУМУ БАЗИ — НАПРУГА НА ЗАТВОРІ ---
  //  Те саме за суттю («ключ мусить бути повністю відкритий»), але міряється
  //  зовсім іншою величиною. Рахуємо на НИЖНІЙ межі допуску живлення: дільник
  //  живиться від тієї ж шини, тож просілий блок ослабляє й керування
  //  затвором. Запас ×3/2 над VGS(th) max — бо поріг паспортний дається при
  //  мізерному струмі стоку (250 мкА), а нам треба одиниці ампер.
  #if (CHARGE_MOS_VGS_AT_MIN_PSU_MV) < ((CHARGE_MOS_VGSTH_MAX_MV) * 3 / 2)
    #error "На нижній межі допуску живлення напруги на затворі замало, щоб надійно відкрити MOSFET (потрібно щонайменше 1.5×VGS(th) max). Зменште CHARGE_BASE_DRIVE_OHM, підніміть CHARGE_BASE_PULLUP_OHM або підніміть CHARGE_PSU_MIN_MV."
  #endif
  //  І симетрична межа зверху: затвор-витік має абсолютний максимум, а
  //  дільник живиться від тієї ж шини, тож найгірший випадок — CHARGE_PSU_MAX_MV.
  //  Пробитий затвор — це відмова НАЗАВЖДИ і одразу в коротке замикання.
  #if (CHARGE_MOS_VGS_AT_MAX_PSU_MV) > ((CHARGE_MOS_VGS_MAX_MV) * 4 / 5)
    #error "На верхній межі допуску живлення напруга затвор-витік перевищує 80 % абсолютного максимуму MOSFET. Підніміть CHARGE_BASE_DRIVE_OHM, опустіть CHARGE_PSU_MAX_MV або поставте стабілітрон на затворі."
  #endif
  //  Ключ мусить витримати напругу шини й у закритому стані.
  #if (CHARGE_PSU_MAX_MV) > ((CHARGE_MOS_VDS_MAX_MV) * 4 / 5)
    #error "Напруга живлення перевищує 80 % Vds max польового ключа."
  #endif
  //  ⚑ ВИМИКАННЯ — НАЙПОВІЛЬНІША ЧАСТИНА, і саме воно палить польовий ключ.
  //  Угору затвор тягне ЛИШЕ запираюча підтяжка (дільник у цей час
  //  розімкнений), тож її номінал напряму задає час, який ключ проводить у
  //  лінійному режимі під повною напругою. Якщо перемикання займає більш ніж
  //  десяту частину періоду, транзистор більшу частину часу не «ключ», а
  //  резистор під 14 В.
  #if ((CHARGE_MOS_TSW_NS) * (CHARGE_PWM_FREQ)) > (100000000L)
    #error "Перемикання займає понад 10 % періоду ШІМ: затвор перезаряджається надто повільно. Зменште CHARGE_BASE_PULLUP_OHM (швидше запирання), знизьте CHARGE_PWM_FREQ або візьміть MOSFET із меншим Qg."
  #endif
#endif

  // --- ДРАЙВЕРНИЙ КАСКАД: керуючий NPN теж мусить НАСИЧУВАТИСЬ ---
  //  Через його колектор тече ВЕСЬ струм бази PNP. Якщо він сам не в
  //  насиченні, на ньому падає вольт замість 0.2 В, струм бази PNP просідає,
  //  і з насичення виходить уже СИЛОВИЙ ключ. Відмова каскадна, тому
  //  перевіряємо обидві ланки, а не лише силову.
  //  (CHARGE_NPN_IB_UA визначено вгорі блока, разом з іншими розрахунковими
  //  величинами — його читає ще й перевірка живлення, яка йде раніше.)
  //  Через колектор NPN тече ВЕСЬ струм драйвера (разом із тим, що потім
  //  відбере підтяжка), тому тут CHARGE_BASE_DRIVE_UA, а не CHARGE_IB_MA.
#if CHARGE_SW_IS_BJT
  #if (CHARGE_NPN_IB_UA) < ((CHARGE_BASE_DRIVE_UA) / (CHARGE_NPN_HFE_FORCED))
    #error "Керуючий NPN не насититься: струму його бази замало під струм драйвера силового ключа. Зменште CHARGE_NPN_BASE_OHM (для 86 мА колектора підходить 470 Ом; на платі стоїть 20 кОм — його треба перепаяти)."
  #endif
#else
  //  ⚑ ТОЙ САМИЙ КАСКАДНИЙ ЗАПОБІЖНИК, АЛЕ ПІД ІНШИЙ СТРУМ. З польовим ключем
  //  через колектор NPN тече не струм бази, а наскрізний струм ДІЛЬНИКА, і
  //  найгірший він на ВЕРХНІЙ межі допуску живлення. Якщо NPN тут не
  //  насититься, на ньому лишиться вольт замість 0.2 В — затвор не досягне
  //  потрібної напруги, і в лінійний режим піде вже силовий ключ.
  //  ⚠️ Саме ця перевірка й не пускає плату з нинішнім 20 кОм у базі NPN:
  //  0.13 мА бази проти потрібних ~0.4 мА. Заміна польовим ключем цієї
  //  вимоги НЕ скасовує.
  #if (CHARGE_NPN_IB_UA) < ((CHARGE_MOS_IDIV_AT_MAX_PSU_UA) / (CHARGE_NPN_HFE_FORCED))
    #error "Керуючий NPN не насититься: струму його бази замало під наскрізний струм дільника затвора на верхній межі живлення. Зменште CHARGE_NPN_BASE_OHM (20 кОм на платі треба перепаяти) або підніміть номінали дільника."
  #endif
  #if (CHARGE_MOS_IDIV_AT_MAX_PSU_UA) > (CHARGE_NPN_IC_MAX_MA) * 1000
    #error "Наскрізний струм дільника затвора перевищує Ic max керуючого NPN."
  #endif
#endif
  //  І цей струм мусить лишатись у межах того, що пін ESP32 віддає безпечно.
  //  Однаково для обох ключів: пін живить базу NPN, а не сам ключ.
  #if (CHARGE_NPN_IB_UA) > (CHARGE_GPIO_UA_MAX)
    #error "Струм із піна на базу керуючого NPN перевищує безпечний для ESP32. Підніміть CHARGE_NPN_BASE_OHM."
  #endif

#if CHARGE_SW_IS_BJT
  //  --- запираюча підтяжка не має з'їдати драйвер ---
  //  Вона потрібна (тримає ключ закритим у спокої й прискорює вимикання), але
  //  надто мала перетворює драйвер на грілку: струм тече повз базу.
  //  ⚑ Для ПОЛЬОВОГО ключа такої перевірки немає й бути не може: там підтяжка
  //  нічого не «відбирає» — вона є нижнім плечем дільника, який і задає
  //  напругу на затворі, тобто її струм і є керування. Обмежує її не витік, а
  //  час вимикання (перевірка вище) і нагрів (нижче).
  #if (CHARGE_BASE_BLEED_UA) * 5 > (CHARGE_BASE_DRIVE_UA)
    #error "Запираюча підтяжка CHARGE_BASE_PULLUP_OHM відбирає понад 20 % струму драйвера. Підніміть її номінал."
  #endif
#else
  //  Замість цього — нагрів самої підтяжки: через неї тече весь наскрізний
  //  струм дільника, поки ключ відкритий. P = I²R.
  #if (((CHARGE_MOS_IDIV_AT_MAX_PSU_UA) / 1000) * \
       ((CHARGE_MOS_IDIV_AT_MAX_PSU_UA) / 1000) * (CHARGE_BASE_PULLUP_OHM) / 1000) > 250
    #error "Запираюча підтяжка розсіює понад 0.25 Вт наскрізного струму дільника затвора — потрібен резистор більшої потужності або більші номінали дільника."
  #endif
#endif

  // --- ВИПЕРЕДЖЕННЯ ENABLE мусить бути помітним, але не блокувати старт ---
  //  Нуль означав би, що вимір іде одночасно з під'єднанням пакета — тобто
  //  повернення до тієї самої хибної «перенапруги». Занадто велика пауза —
  //  це блокуючий delay() у відповіді веб-серверу.
  #if (CHARGE_ENABLE_LEAD_MS) < 20
    #error "CHARGE_ENABLE_LEAD_MS замалий: пакет не встигне під'єднати клеми, і перший вимір потрапить у розімкнене коло (подільник покаже стелю, заряд оголосить хибну перенапругу)."
  #endif
  #if (CHARGE_ENABLE_LEAD_MS) > 1000
    #error "CHARGE_ENABLE_LEAD_MS завеликий: це блокуюча пауза в обробнику запиту на старт заряду."
  #endif
  //  І вона мусить лишатись помітно коротшою за період опитування — інакше
  //  старт з'їдав би цілий такт регулятора.
  #if (CHARGE_ENABLE_LEAD_MS) * 2 > (CHARGE_POLL_MS)
    #error "CHARGE_ENABLE_LEAD_MS порівнянний із CHARGE_POLL_MS — пауза перед стартом з'їдає такт опитування."
  #endif

  // --- ДОЗАРЯД МАЛИМ СТРУМОМ: пороги мусять іти в правильному порядку ---
  //  Спад струму ділить профіль на «крейсер» і «дозаряд». Якщо поріг залізе
  //  на плато 80 % або вище за 100 %, відрізок дозаряду або з'їсть плато, або
  //  зникне зовсім — і те, й те тихо, без жодного симптому в журналі.
  #if (CHARGE_TAPER_PCT) <= 80 || (CHARGE_TAPER_PCT) >= 100
    #error "CHARGE_TAPER_PCT мусить лежати між 80 % (кінець розгону) і 100 % (ціль): інакше відрізок дозаряду малим струмом або поглинає плато, або зникає."
  #endif
  //  Індикатор не має права показувати «крейсерський заряд», коли пристрій
  //  уже перейшов на дозаряд: світлодіод — єдине, що видно без екрана.
  #if (CHARGE_LED_TAPER_PCT) > (CHARGE_TAPER_PCT)
    #error "CHARGE_LED_TAPER_PCT пізніший за CHARGE_TAPER_PCT: індикатор показував би крейсерський заряд, коли струм уже впав до дозарядного."
  #endif
  //  Дозарядний струм мусить бути справді МАЛИМ проти крейсерського —
  //  інакше «дозаряд» лише називається так.
  #if (CHARGE_MA_TAPER) * 3 > (CHARGE_MA_80)
    #error "CHARGE_MA_TAPER не менший за третину CHARGE_MA_80 — це не дозаряд малим струмом, а той самий крейсерський режим під іншою назвою."
  #endif

  // --- ЦІЛЬ ЗАРЯДУ мусить лишатись усередині шкали паливоміра ---
  //  Заряджати вище верхньої межі шкали не можна (нема куди рахувати
  //  відсотки), а нижче за порожній пакет — безглуздо.
  #if (CHARGE_TARGET_MV) > (BATTERY_FULL_MV)
    #error "CHARGE_TARGET_MV вище за BATTERY_FULL_MV: ціль заряду виходить за верх шкали паливоміра. Піднімайте шкалу, а не ціль."
  #endif
  #if (CHARGE_TARGET_MV) <= (BATTERY_EMPTY_MV)
    #error "CHARGE_TARGET_MV не вище за BATTERY_EMPTY_MV — заряджати нікуди."
  #endif
  //  І ціль мусить лишатись вище за напругу, до якої САДИТЬ розряд: інакше
  //  два режими тягли б пакет у різні боки без кінця.
  #if (CHARGE_TARGET_MV) <= (DISCHARGE_TARGET_MV)
    #error "CHARGE_TARGET_MV не вище за DISCHARGE_TARGET_MV: заряд і розряд мали б протилежні цілі."
  #endif

  // --- «ПАКЕТ ЗАКРИВСЯ САМ»: допуск не сміє поглинути аварійну межу ---
  //  Якщо допуск «повного» дотягнеться до аварійної межі, то будь-яке
  //  розмикання пакета — навіть на 7 В через власну несправність — буде
  //  зараховане як успішно завершений заряд. Діагноз «пакет розімкнув захист
  //  не за напругою» (CHGR_PACKOPEN) при цьому стане недосяжним, і про
  //  несправний пакет власник дізнається як про «заряд завершено».
  #if (CHARGE_PACKFULL_TOL_MV) >= ((CHARGE_TARGET_MV) - (DISCHARGE_TARGET_MV))
    #error "CHARGE_PACKFULL_TOL_MV ширший за проміжок між ціллю заряду й ціллю розряду: розряджений пакет, що сам розімкнувся, буде оголошений повним. Звузьте допуск."
  #endif
  //  Вікно частого читання монітора мусить бути НЕ ВУЖЧИМ за допуск: інакше
  //  пакет закриється сам іще до того, як ми почнемо читати монітор щосекунди,
  //  і рішення доведеться приймати за показом, якому вже кілька опитувань.
  #if (CHARGE_CHIP_WATCH_MV) < (CHARGE_PACKFULL_TOL_MV)
    #error "CHARGE_CHIP_WATCH_MV вужчий за CHARGE_PACKFULL_TOL_MV: у зоні, де пакет уже має право закритися сам, монітор ще читається рідко. Розширте вікно спостереження."
  #endif

  // --- ПІКОВИЙ СТРУМ у межах паспортного максимуму ключа ---
  #if (CHARGE_IPEAK_MA) > (CHARGE_SW_IMAX_MA)
    #error "Вершина пульсацій перевищує паспортний максимальний струм силового ключа. Знизьте CHARGE_MA_80 або зменште пульсації (більший CHARGE_L_UH / вища CHARGE_PWM_FREQ)."
  #endif

  // --- РОЗСІЮВАННЯ НА КЛЮЧІ в межах Pc ---
  //  Дві складові, і в біполярника ОБИДВІ значні:
  //   • провідна:   Uке_нас × Iк × D;
  //   • перемикальна: ½ × Uживл × Iк × tsw × f — саме вона зазвичай і домінує,
  //     бо розсмоктування заряду бази триває мікросекунди.
  //  Беремо 80 % від Pc: паспортне значення дане для корпусу при 25 °C, і без
  //  радіатора реальна межа помітно нижча.
  //  1LL — щоб макрос лишався правильним і поза #if: у препроцесорі рахунок
  //  іде в intmax_t, а у звичайному коді 500 × 1000 × 8250 не влазить у int.
#if CHARGE_SW_IS_MOS
  //  ⚑ У ПОЛЬОВОГО ПРОВІДНІ ВТРАТИ — I²R, А НЕ I×U. Це не дрібниця форми
  //  запису: у біполярника падіння майже не залежить від струму, тож втрати
  //  ростуть ЛІНІЙНО, а тут — КВАДРАТИЧНО. Подвоїте струм заряду — втрати на
  //  ключі вчетверо. Підставити сюди стару формулу означало б отримати
  //  зручне, але неправильне число саме там, де воно вирішує долю ключа.
  #define CHARGE_P_COND_MW \
      ((CHARGE_MA_80) * 1LL * (CHARGE_MA_80) * (CHARGE_MOS_RDSON_MOHM) / 1000000LL * \
       (CHARGE_TARGET_MV) / (CHARGE_SUPPLY_MV))
#else
  #define CHARGE_P_COND_MW \
      ((CHARGE_BJT_VCE_SAT_MV) * 1LL * (CHARGE_MA_80) * (CHARGE_TARGET_MV) / \
       ((CHARGE_SUPPLY_MV) * 1000LL))
#endif
  //  Перемикальні втрати рахуються однаково, різниця лише в тому, звідки
  //  береться tsw: у біполярника це розсмоктування заряду бази (паспортна
  //  оцінка), у польового — час, за який НАШ драйвер перезаряджає Qg.
  #define CHARGE_P_SW_MW \
      ((CHARGE_SUPPLY_MV) * 1LL * (CHARGE_MA_80) * (CHARGE_SW_TSW_NS) * \
       (CHARGE_PWM_FREQ) / 2000000000000LL)
  #if ((CHARGE_P_COND_MW) + (CHARGE_P_SW_MW)) > ((CHARGE_SW_PD_MW) * 4 / 5)
    #error "Розсіювання на силовому ключі перевищує 80 % його паспортної потужності. Знизьте CHARGE_MA_80, прискорте перемикання (менший CHARGE_BASE_PULLUP_OHM для MOSFET / активне запирання бази для BJT) або знизьте CHARGE_PWM_FREQ."
  #endif

  // --- ПУЛЬСАЦІЇ ДРОСЕЛЯ не мають перевищувати робочий струм ---
  //  ΔI = (Uживл − Uвих) × D / (L × f). Найгірший штатний випадок беремо
  //  просто: D ≈ Uвих/Uживл на цілі, тобто
  //     ΔI ≈ Uвих × (Uживл − Uвих) / (Uживл × L × f).
  //  Якщо розмах перевищує найбільшу уставку струму, перетворювач більшу
  //  частину часу в переривчастому режимі: регулювати такий струм важко, а
  //  пік удвічі вищий за середнє.
  #if ((CHARGE_RIPPLE_MA_EST) / 2) > (CHARGE_MA_80)
    #error "Крейсерська уставка нижча за межу неперервного режиму (ΔI/2): перетворювач працював би в переривчастому режимі з удвічі вищим піком. Підніміть CHARGE_L_UH або CHARGE_PWM_FREQ."
  #endif
  #if (CHARGE_IPEAK_MA) >= (CHARGE_PEAK_MA_MAX)
    #error "Штатна вершина пульсацій (уставка + ΔI/2) дотягується до аварійної відсічки CHARGE_PEAK_MA_MAX — заряд спинявся б на нормальному режимі. Підніміть відсічку або зменште пульсації."
  #endif

  // --- СТЕЛІ ШПАРУВАТОСТІ мусить вистачати, щоб ДОТЯГТИСЯ до цілі ---
  //  Uвих ≈ D × Uживл, і до напруги пакета треба ще додати падіння на шунті
  //  при найбільшому струмі. Замала стеля означає, що заряд не дійде до цілі
  //  й упреться в стелю часу — а виглядає це як «заряд не працює».
  #if (((CHARGE_SUPPLY_MV) * (CHARGE_DUTY_MAX_PCT) / 100) < \
       ((CHARGE_TARGET_MV) + (CHARGE_MA_80) * (CHARGE_SHUNT_MOHM) / 1000))
    #error "CHARGE_DUTY_MAX_PCT замала: D×Uживл не дотягується до цілі плюс падіння на шунті. Підніміть стелю або напругу живлення."
  #endif
#endif

