//  каскадна: NPN не насичується -> на ньому падає вольт замість 0.2 В ->
//  струм бази PNP просідає -> з насичення виходить СИЛОВИЙ ключ і згорає.
#define CHARGE_NPN_BASE_OHM     470
#define CHARGE_NPN_VBE_MV       700
// Форсований коефіцієнт для керуючого NPN. 20 — надійне насичення для
// сигнального транзистора з hFE >= 100 на цьому струмі.
#define CHARGE_NPN_HFE_FORCED   20
// Напруга логічної одиниці на піні, мВ, і безпечний струм із піна ESP32.
#define CHARGE_GPIO_MV          3300
#define CHARGE_GPIO_UA_MAX      20000
// Робоча стеля входу АЦП ESP32, мВ (атенюація 11 дБ). Вище — показання
// «залипають» на 4095.
#define CHARGE_ADC_MAX_MV       3100
