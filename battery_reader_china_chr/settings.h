  //  споживає, тож поки керуючий NPN відкритий, на затворі стоїть просто
  //
  //      Uзатв = Uке_нас(npn) + (Uживл − Uке_нас) × R_drive/(R_drive + R_підт)
  //
  //  а напруга керування — це різниця між витоком (він на +14 В) і затвором.
  //  Звідси й береться вся арифметика нижче. Для біполярника ці ж резистори
