#define CHARGE_NPN_VCE_SAT_MV   200

// Запираючий резистор база-емітер PNP, Ом — тримає ключ закритим у спокої й
// прискорює розсмоктування заряду бази при вимиканні.
//  ⚑ Він же ВІДБИРАЄ частину струму драйвера: поки ключ відкритий, через
//  нього тече Uбе/R_підт (при 1 кОм — 0.9 мА), і ці міліампери до бази вже не
//  доходять. На 1 кОм це 1 % від 86 мА — дрібниця, але у формулі струму бази
//  нижче враховано, бо на дрібнішій підтяжці витік став би відчутним.
#define CHARGE_BASE_PULLUP_OHM  1000

// ── ДРАЙВЕРНИЙ КАСКАД: керуючий NPN між піном і базою силового PNP ────────
//  Резистор від піна до бази NPN.
//
//  ⚠️⚠️ НА ПЛАТІ ЗАРАЗ СТОЇТЬ 20 кОм — ЦЕ ТРЕБА ЗАМІНИТИ НА 390 Ом.
//  20 кОм — типовий номінал, коли NPN просто вмикає світлодіод чи реле; тут
//  через його колектор тече ВЕСЬ струм бази силового ключа, і арифметика
//  зовсім інша:
//     Iб(NPN) = (3.3 − 0.7)/20000 = 0.13 мА.
//  Це стеля колектора 2.6 мА при β_форс 20 — тобто керуючий каскад сам не
//  здатен віддати навіть тих 12.9 мА, які тече через нинішній базовий
//  резистор 1 кОм (β_форс вийшов би 99 — «як пощастить із партією»), не
//  кажучи вже про 106 мА після його заміни на 120 Ом.
//  Відмова КАСКАДНА і завжди в один бік: NPN не насичується -> на ньому
//  лишається вольт замість 0.2 В -> струм бази PNP просідає -> з насичення
//  виходить уже СИЛОВИЙ ключ -> B772M працює в лінійному режимі під 14 В і
//  згорає за секунди.
//
//  ⚑ ЧОМУ 390 Ом, А НЕ 470. Тут найгірший випадок — ВЕРХНЯ межа допуску
//  живлення (CHARGE_PSU_MAX_MV = 16 В): чим вище живлення, тим більший струм
//  драйвера мусить пропустити NPN (при 16 В і 120 Ом це 124 мА, тобто 6.2 мА
//  в базу при β_форс 20). 470 Ом дають 5.5 мА — вистачає рівно на номінальні
//  14 В і вже ні на що більше. 390 Ом дають 6.7 мА, і з піна це все ще лише
//  третина від дозволених 20 мА.
#define CHARGE_NPN_BASE_OHM     390
#define CHARGE_NPN_VBE_MV       700
// Форсований коефіцієнт для керуючого NPN. 20 — надійне насичення для
