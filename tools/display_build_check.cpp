// ===========================================================================
//  Доти драйвер екрана був ЄДИНИМ великим файлом проєкту без жодної збірки на
//  хості: усі перевірки для нього — текстові («чи є в файлі такий виклик»), а
//  текст не бачить ні описки в імені, ні зайвої дужки, ні звернення до поля,
//  якого немає. Знаходилось це вже в Arduino IDE — тобто після того, як
//  прошивку залили в прилад. Один раз саме так і вийшло: власник побачив
//  чорний екран і день пішов на розбір, чи винна правка.
//
//  ⚑ ЩО САМЕ ПЕРЕВІРЯЄТЬСЯ. Складання ST7789 — те, що стоїть у власника
//  (settings.h). Монохромний шлях (u8g2) сюди НЕ входить: у нього десяток
//  класів на кожну модель екрана, і заглушки до них коштували б більше, ніж
//  дають. Це чесно сказано й у виводі — щоб «зелено» не читалось як «усе
//  покрито».
//
//  Малюють заглушки в нікуди (tools/fake/): картинку перевірити на хості
//  однаково неможливо, а от синтаксис і імена — цілком.
// ===========================================================================
