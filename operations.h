// Заповнює name/l1/l2/danger для пункту меню sel. buf — тимчасовий буфер під
// назви з моделлю («Модель PMNN4409B»), потрібен ≥26 байт.
inline void opInfo(int sel, const char **name, const char **l1, const char **l2,
                   uint8_t *danger, char *buf, size_t bufN, uint8_t *chips = nullptr) {
    uint8_t c = OPC_NONE;
    if (sel >= 0 && sel < OP_BASE_COUNT) {
        *name = OP_TEXT[sel].name; *l1 = OP_TEXT[sel].l1;
        *l2 = OP_TEXT[sel].l2;     *danger = OP_TEXT[sel].danger;
        c = OP_TEXT[sel].chips;
        // Обидва пункти розряду показують ОБРАНУ ціль прямо в назві: інакше на
        // пристрої не видно, до якої напруги піде розряд.
        if (sel == OP_DISCHARGE) {
            snprintf(buf, bufN, "Розряд %.2f В", dischargeTargetMv() / 1000.0);
            *name = buf;
        } else if (sel == OP_DISCHARGE_TGT) {
            snprintf(buf, bufN, "Ціль %.2f В", dischargeTargetMv() / 1000.0);
            *name = buf;
        }
        if (chips) *chips = c;
        return;
    }
    int t = opTemplateOfModel(sel);
    if (t >= 0) {
        snprintf(buf, bufN, "Модель %s", BATTERY_TEMPLATES[t].name);
        *name = buf; *l1 = "записати модельну"; *l2 = "частину еталона";
        *danger = OPD_WRITE;
        // Для моделей без еталона монітора пишеться лише DS2433 — монітор
        // пакета лишається недоторканим разом із його заводським шунтом.
        if (chips) *chips = BATTERY_TEMPLATES[t].d38 ? OPC_BOTH : OPC_33;
        return;
    }
    t = opTemplateOfNew(sel);
    if (t >= 0) {
        snprintf(buf, bufN, "Новий %s", BATTERY_TEMPLATES[t].name);
        *name = buf; *l1 = "порожній чіп ->"; *l2 = "робочий АКБ моделі";
        *danger = OPD_WIPE;
        if (chips) *chips = OPC_BOTH;
        return;
    }
    int e = opExpert(sel);
    if (e >= 0) {
        *name = OP_TEXT_EXPERT[e].name; *l1 = OP_TEXT_EXPERT[e].l1;
        *l2 = OP_TEXT_EXPERT[e].l2;     *danger = OP_TEXT_EXPERT[e].danger;
        if (chips) *chips = OP_TEXT_EXPERT[e].chips;
        return;
    }
    *name = "—"; *l1 = ""; *l2 = ""; *danger = OPD_SAFE;
    if (chips) *chips = OPC_NONE;
}

