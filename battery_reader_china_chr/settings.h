//  35 і 34 — ВХІД-ТІЛЬКИ (input-only) і належать до ADC1. Обидві властивості
//  тут доречні: вихідного драйвера в них немає взагалі, тож вимірювальну лінію
//  фізично неможливо випадково «продавити» назовні; а ADC1, на відміну від
