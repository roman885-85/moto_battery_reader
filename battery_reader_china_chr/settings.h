#define CHARGE_NPN_HFE_FORCED   20
// Паспортний Ic max керуючого NPN, мА. За замовчуванням — 2N2222/BC337/S8050
// (усі 0.6…0.8 А). Поставите BC547 (100 мА) — перевірка нижче це зловить.
#define CHARGE_NPN_IC_MAX_MA    600

