//  Розряд — єдиний режим, де пристрій тримає замкнутим силовий ключ І сигнал
//  enable без участі людини. Якщо головний цикл зависне (збій Wi-Fi-стека,
//  нескінченне очікування на шині, будь-що), ключ так і лишиться відкритим, а
//  пакет саджатиметься в нуль. Тому на час розряду вмикається сторож:
//
//   • ПРОГРАМНИЙ. Якщо між опитуваннями минуло більше DISCHARGE_STALL_MS —
//     цикл десь застряг, але ще живий: розряд аварійно зупиняється, ключ
//     закривається, enable знімається. Поріг — із запасом на найдовшу штатну
//     затримку (запис DS2433 — 16 сторінок по 10 мс + службові операції).
//   • АПАРАТНИЙ. Якщо цикл не живий узагалі, програмний сторож не спрацює.
//     Тоді ESP32 перезавантажується за Task WDT. Після скидання піни — входи,
