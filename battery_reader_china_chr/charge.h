// Накопичена ємність, мА*год (наш інтеграл виміряного струму по опитуваннях).
inline uint32_t chargeMah() { return g_chg.mahX1000 / 1000; }

// Один крок інтеграла ємності: додати мА за проміжок dtMs, НЕ ГУБЛЯЧИ залишку.
//
// ⚑ Навіщо залишок узагалі. Доданок дорівнює мА×мс/3600, і при кроці 25 мс
// (пробудження) він менший за одиницю на будь-якому струмі до 144 мА. Просте
// цілочисельне ділення з'їдало б його повністю: лічильник відданої ємності
// стояв би на нулі рівно в тому режимі, де він і є запобіжником. При кроці 1 с
// (штатний заряд) цього не видно — там доданок завжди цілий, — тому й помітити
// це можна було лише на короткому кроці.
//
// Чиста функція з посиланнями: хостовий тест ганяє її напряму, а не через
// chargeTask(), якого на хості немає.
inline void chargeAccumMah(uint32_t *mahX1000, uint32_t *rem, int32_t ma, uint32_t dtMs) {
    if (ma < 0) ma = -ma;
    uint32_t num = (uint32_t)ma * dtMs + *rem;
    *mahX1000 += num / 3600UL;
    *rem       = num % 3600UL;
}

// Те саме за АПАРАТНИМ лічильником CCA DS2438 (ціна розряду — 15.625 мВ*год,
// як і DCA в розряду).
//
// ⚑ Тепер це справді НЕЗАЛЕЖНА перевірка, а не переспів того самого числа:
// наш інтеграл рахується з ВЛАСНОГО шунта (CHARGE_SHUNT_MOHM), а CCA — з
// шунта ПАКЕТА всередині DS2438. Два різні давачі на одному струмі: велика
// розбіжність означає, що один із них бреше.
inline uint32_t chargeCcaMah() {
    uint16_t delta = (uint16_t)(g_chg.lastCca - g_chg.startCca);   // з урахуванням переповнення
    float rs = g_chg.rsense > 0.0f ? g_chg.rsense : DS2438_RSENSE_OHM;
    return (uint32_t)(15.625f * delta / rs);
}

inline int chargeWattsX10(uint16_t mv, int16_t ma) {
    long w = ((long)mv * (ma < 0 ? -ma : ma)) / 100000L;
    return (int)w;
}

