#define CHARGE_MA_START   200
#define CHARGE_MA_10      400
#define CHARGE_MA_50      700
#define CHARGE_MA_80      1000
#define CHARGE_MA_TAPER   100

// Мінімальна дозволена ЦІЛЬ заряду, % — нижче не пускаємо: занадто малий
// заряд не має сенсу, і на дуже малих цілях перерахунок точок перегину
// профілю (chargeSetpointMaForPct) вироджується (надто вузькі відрізки).
#define CHARGE_TARGET_PCT_MIN 50

// Поріг переходу індикатора на часте блимання (LED_CHARGE_TAPER), % — власна
// межа для СВІТЛОДІОДА, окрема від 95 % у профілі струму вище: «майже
// готово» на індикаторі мусить впадати в очі трохи РАНІШЕ, ніж сам
// ступінчастий спад струму.
#define CHARGE_LED_TAPER_PCT 90

// Максимально можлива ціль (= «100 %» на повзунку), мВ. = BATTERY_FULL_MV.
#define CHARGE_TARGET_MV    BATTERY_FULL_MV

// АВАРІЙНА стеля напруги ПОНАД ціль ЦЬОГО СЕАНСУ — запобіжник від «контур
