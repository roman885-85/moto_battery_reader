# -*- coding: utf-8 -*-
import io
import json
import os
import re
"""СПИСОК МОДЕЛЕЙ-ЕТАЛОНІВ: що показувати після відповіді на TEMPLATES.

⚑ ЧОМУ ЦЕ ОКРЕМИЙ ФАЙЛ, А НЕ ТРИ РЯДКИ В moto_gui.py.

Тут немає жодного віджета — і це головна властивість модуля, а не випадковість.
moto_gui.py імпортує tkinter уже в заголовку й будує класи на його основі, тож
на збірковій машині (де вікон немає, а часто немає й самого tkinter) його
неможливо навіть імпортувати. Усе, написане прямо в обробниках, там не покриває
жоден тест — і саме тому дефект нижче прожив непоміченим до скарги власника.

ДЕФЕКТ, ЯКИЙ ЦЕЙ МОДУЛЬ ЗАКРИВАЄ. Скарга: «в exe при відновленні з еталона в
Майстрі у випадному списку не показуються еталони». Причина була не в Майстрі.
Список приходить командою TEMPLATES РІВНО ОДИН РАЗ — у мить під'єднання, — а
відповідь оброблялась так:

    models = r.get("models", []) if r.get("ok") else []
    for cb in (...): cb["values"] = models

Тобто будь-яка невдала відповідь (таймаут, зайнята шина, обірваний кабель)
мовчки затирала вже завантажений список порожнім. Другого шляху до TEMPLATES в
інтерфейсі не було, тож вийти з цього стану можна було лише перепідключенням —
про яке ніде не сказано. Людина бачила порожній список і напис «Оберіть модель
для відновлення»: вимогу, яку неможливо виконати.

Веб-клієнти тієї біди не мали з двох причин: вони питають моделі ПІСЛЯ повного
оновлення (await refresh(); await loadTemplates()), а не пачкою одразу після
відкриття порту, і показують «(немає шаблонів)», коли список порожній.
"""

# Написи-заглушки. Їх ДВА навмисно: «список не приїхав» і «у прошивці шаблонів
# немає» — це протилежні поради (перше лікується повтором, друге прошивкою), а
# порожній список однаково мовчить про обидва.
TPL_NONE_FW    = "(у прошивці немає шаблонів)"
TPL_NOT_LOADED = "(список не завантажено — натисніть 🔄)"


def templates_from_reply(reply, current):
    """Що покласти у списки моделей після відповіді на TEMPLATES.

    Повертає (models, note):
      • models — що показати. ПОРОЖНІМ цей список не буває ніколи: або
        справжні моделі, або рівно один напис, який пояснює, чого немає;
      • note   — рядок для смуги стану, або None, коли все гаразд.
    """
    ok = bool(reply.get("ok")) if isinstance(reply, dict) else False
    models = list(reply.get("models") or []) if ok else []

    if ok and models:
        return models, None
    if ok:
        # Прошивка відповіла, і відповідь чесна: шаблонів у ній справді немає.
        return [TPL_NONE_FW], "Прошивка не має жодного шаблону моделі"

    # Відповіді не було. Уже завантажений список — це ЄДИНЕ, що ми про моделі
    # знаємо, і викидати його через один таймаут не можна: він не застарів, він
    # просто не підтвердився.
    err = (reply.get("err") if isinstance(reply, dict) else None) or "немає відповіді"
    keep = [m for m in (current or []) if m not in (TPL_NONE_FW, TPL_NOT_LOADED)]
    if keep:
        return keep, "Список моделей не оновився (%s) — лишили попередній" % err
    return [TPL_NOT_LOADED], "Список моделей не завантажився (%s)" % err


def templates_pick_valid(models):
    """Пункти, які справді можна ВИБРАТИ (тобто без заглушок).

    Потрібно окремою функцією, бо «список не порожній» і «є що вибрати» — різні
    твердження рівно відтоді, як у списку з'явились пояснювальні написи.
    """
    return [m for m in (models or []) if m not in (TPL_NONE_FW, TPL_NOT_LOADED)]



# ── СПИСОК ПОРТІВ: BLUETOOTH ВИГЛЯДАЄ ЯК ДВА ОДНАКОВІ РЯДКИ ───────────────
#  Спарувавши прилад, Windows заводить ДВА послідовні порти на одне з'єднання:
#  ВИХІДНИЙ (ним під'єднуються до приладу) і ВХІДНИЙ (ним прилад під'єднувався
#  б до комп'ютера — нам він не потрібен ніколи). Опис у системи в обох
#  однаковий — «Standard Serial over Bluetooth link», — тож у випадному списку
#  вони виглядали як два невідрізнимі рядки, і вибір між ними був підкиданням
#  монетки. Обравши вхідний, людина дістає відмову відкриття й жодної підказки,
#  ЧОМУ саме.
#
#  ⚑ ЩО ТУТ ВІДОМО ТОЧНО, А ЩО — ЛИШЕ СХОЖЕ. Ознака «це Bluetooth» надійна:
#  префікс BTHENUM в апаратному ідентифікаторі є в обох портів пари й у жодного
#  USB-перехідника. А от «вихідний чи вхідний» ми читаємо з адреси всередині
#  hwid: у вихідного там стоїть адреса ПРИЛАДУ, у вхідного — нулі. Це
#  спостереження, а не документований формат, тому підпис каже «схоже на», а
#  остаточну відповідь дає сама Windows (Параметри Bluetooth → Додаткові
#  параметри → вкладка «COM-порти», стовпчик «Напрямок»).
#
#  ⚑ І САМЕ ТОМУ ЦЕ ТУТ, А НЕ В ОБРОБНИКУ. moto_gui.py імпортує tkinter у
#  заголовку й на збірковій машині не імпортується взагалі; написане всередині
#  refresh_ports() не покривав би жоден тест — рівно та історія, що з порожнім
#  списком еталонів (3.56).
def port_is_bluetooth(hwid):
    return "BTHENUM" in (hwid or "").upper()


# Адреса приладу з hwid: 12 шістнадцяткових цифр, за якими стоїть «_».
#
#  ⚑ САМЕ «ЗА ЯКИМИ СТОЇТЬ _», А НЕ ПРОСТО 12 ЦИФР. Перша редакція шукала
#  будь-який такий рядок — і знаходила ХВІСТ GUID послідовного сервісу
#  ({00001101-…-00805F9B34FB}), однаковий геть в усіх Bluetooth-портів. Обидва
#  порти пари через це виглядали «вихідними», тобто перевірка підказувала те
#  саме, що й до неї. Впіймалось це рівно тому, що функцію одразу прогнали на
#  двох справжніх ідентифікаторах, а не на одному.
def port_bt_addr(hwid):
    if not port_is_bluetooth(hwid):
        return ""
    m = re.search(r"[&\\]([0-9A-F]{12})_", (hwid or "").upper())
    return m.group(1) if m else ""


# Чи СХОЖИЙ порт на вихідний канал. None — це взагалі не Bluetooth; None і
# «ні» тут різні відповіді, плутати їх не можна.
def port_bt_outgoing(hwid):
    if not port_is_bluetooth(hwid):
        return None
    a = port_bt_addr(hwid)
    if not a:
        return None            # адреси немає — судити нема з чого
    return a.strip("0") != ""  # усі нулі -> локальний, тобто вхідний


# ── ІМ'Я ПРИЛАДУ В СПИСКУ ПОРТІВ ──────────────────────────────────────────
#  Windows підписує послідовний порт Bluetooth однаково для всіх — «Standard
#  Serial over Bluetooth link», — тож у списку наш прилад нічим не відрізнявся
#  від будь-якого іншого спареного пристрою: людина бачила порт без назви.
#
#  ⚑ ІМ'Я ЗНАЄ ЛИШЕ САМ ПРИЛАД, і питати його нема в кого, доки не з'єднались.
#  Тому клієнт запам'ятовує ім'я за АДРЕСОЮ (її видно в списку портів завжди) і
#  підписує порт починаючи з наступного разу. Скласти ім'я самому з BT_NAME
#  прошивки не можна: це була б друга копія константи по інший бік дроту, і
#  перейменувавши прилад, ми дістали б клієнта, який упевнено показує стару
#  назву. Краще чесне «поки не знаю», ніж упевнена неправда.
def bt_names_path(home):
    """Де лежить пам'ять імен. Окремий файл, а не налаштування програми:
    це не смак користувача, а довідник, який заповнюється сам."""
    return os.path.join(home or ".", ".moto_bt_names.json")


def bt_names_load(path):
    """Немає файла або він побитий — це НЕ помилка: просто ще нічого не знаємо.
    Порожній словник тут чесніший за виняток, бо єдиний наслідок незнання —
    порт підпишеться адресою замість імені."""
    try:
        with io.open(path, "r", encoding="utf-8") as f:
            d = json.load(f)
        return {str(k).upper(): str(v) for k, v in d.items() if k and v}
    except Exception:
        return {}


def bt_names_save(path, names):
    """Не вдалось записати — теж не помилка: наступного разу просто спитаємо
    прилад знову. Падати через довідник, без якого все працює, не можна."""
    try:
        with io.open(path, "w", encoding="utf-8") as f:
            f.write(json.dumps(names or {}, ensure_ascii=False, indent=1))
        return True
    except Exception:
        return False


def bt_names_merge(names, addr, name):
    """Повертає НОВИЙ словник; порожнє ім'я або адресу не запам'ятовує."""
    out = dict(names or {})
    a = (addr or "").upper()
    n = (name or "").strip()
    if a and n:
        out[a] = n
    return out


# Рядок для випадного списку. Два Bluetooth-порти мусять відрізнятись ОЧИМА —
# інакше підказка «оберіть вихідний» не має до чого відноситись.
def port_label(device, description, hwid="", names=None):
    if not port_is_bluetooth(hwid):
        return "%s — %s" % (device, (description or "")[:28])
    out = port_bt_outgoing(hwid)
    a = port_bt_addr(hwid)
    known = (names or {}).get(a.upper()) if a else None
    if out is True:
        return "%s — %s (Bluetooth, вихідний)" % (device, known or a or "прилад")
    if out is False:
        return "%s — Bluetooth, схоже на вхідний" % device
    return "%s — %s (Bluetooth)" % (device, known or "прилад")


# Порада, коли порт не відкрився. Для Bluetooth причина майже завжди одна й та
# сама, і мовчазне «помилка відкриття» лишає людину сам на сам із двома
# однаковими рядками.
def port_open_hint(hwid, err):
    if port_bt_outgoing(hwid) is False:
        return ("схоже, це ВХІДНИЙ Bluetooth-порт — під'єднуватись треба вихідним. "
                "Напрямок видно у Windows: Параметри Bluetooth → Додаткові параметри "
                "→ вкладка «COM-порти»")
    if port_is_bluetooth(hwid):
        return ("перевірте, що прилад увімкнено й у режимі Bluetooth (меню «ЗВ\'ЯЗОК»); "
                "перше з'єднання Windows встановлює кілька секунд. Початкова помилка: " + str(err))
    return err


# ── ЗНАЙТИ ПРИЛАД САМОМУ ──────────────────────────────────────────────────
#  У системі буває десяток COM-портів: перехідники, модеми, віртуальні пари,
#  два порти на кожен спарений Bluetooth-пристрій. Windows підписує їх так, що
#  вгадати наш неможливо, і людина тицяє навмання.
#
#  ⚑ АЛЕ ВГАДУВАТИ Й НЕ ТРЕБА: ПРИЛАД ПРЕДСТАВЛЯЄТЬСЯ САМ. У відповідь на PING
#  він каже своє ім'я в полі "dev" — це є в протоколі від самого початку. Тобто
#  замість «оберіть порт зі списку» правильне питання — «спитати кожен порт,
#  хто він». Свого транспорту для цього вигадувати не потрібно.
#
#  Рядок нижче — ЄДИНЕ, що клієнт знає про прилад наперед, і це частина
#  протоколу (як заголовок пакета), а не копія налаштування: змінити його в
#  прошивці означає змінити протокол, і тоді клієнта правлять свідомо.
PROBE_DEV = "MotoBatteryReader"


def probe_is_our_device(reply):
    """Відповідь на PING — від нашого приладу?"""
    if not isinstance(reply, dict):
        return False
    return reply.get("dev") == PROBE_DEV


def port_probe_order(ports, names=None):
    """Порти в тому порядку, в якому їх варто питати. ports — перелік трійок
    (device, description, hwid).

    ⚑ ВХІДНІ BLUETOOTH-ПОРТИ ВИКИДАЮТЬСЯ ЗОВСІМ, і це не оптимізація. Відкриття
    такого порту не просто марне — воно ВИСНЕ на кілька секунд, а таких портів
    у системі стільки ж, скільки спарених пристроїв. Пошук, який спершу
    впирається в них усі, людина вважатиме зависанням програми.

    Порядок решти — від найімовірнішого: спершу той Bluetooth, чиє ім'я ми вже
    знаємо (це майже напевно наш прилад), потім інший Bluetooth, потім звичайні
    порти.
    """
    known, bt, plain = [], [], []
    for dev, desc, hwid in ports:
        out = port_bt_outgoing(hwid)
        if out is False:
            continue                       # вхідний канал — ніколи не наш
        if out is True:
            a = port_bt_addr(hwid).upper()
            (known if (names or {}).get(a) else bt).append(dev)
        else:
            plain.append(dev)
    return known + bt + plain
