#define ESP_ARDUINO_VERSION ESP_ARDUINO_VERSION_VAL(3, 3, 11)
#define ESP_ARDUINO_VERSION_MAJOR 3

#include "esp32_stubs.h"
#include "display.h"

// Глобали, які в прошивці визначає сам скетч (.ino). Драйвер їх читає, тож
// без них збірка доходить лише до компонувальника — а нам треба перевірити
// саме зібраний файл, а не «майже зібраний».
