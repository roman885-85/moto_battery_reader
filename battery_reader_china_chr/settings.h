#define CHARGE_BJT_TSW_NS       3000

// Резистор, що ЗАДАЄ СТРУМ БАЗИ силового ключа (між колектором NPN і базою
// PNP), Ом. Насичення мусить триматись на ВЕРШИНІ ПУЛЬСАЦІЙ, а не на
// середньому струмі, інакше ключ виходить із насичення на кожному горбі.
//
// ⚠️⚠️ НА ПЛАТІ ЗАРАЗ СТОЇТЬ 1 кОм — ЦЕ ТРЕБА ЗАМІНИТИ НА 120 Ом.
//  Причина не в запасі, а в тому, що з 1 кОм заряд фізично не працює:
//    Iб = (14 − 0.9 − 0.2)/1000 − витік у підтяжку 0.9 мА = 12 мА.
//  При β_форс 20 це стеля колектора 240 мА, а з урахуванням пульсацій
//  дроселя (пік удвічі-втричі вищий за середнє) СЕРЕДНІЙ струм заряду вийшов
//  би ~22 мА. Пакет 2150 мА·год заряджався б ЧОТИРИ ДОБИ. А якщо всупереч
//  цьому виставити більший струм — ключ не насититься, лишиться в лінійному
//  режимі й згорить за секунди.
//
//  ⚑ ЧОМУ 120 Ом, А НЕ 150. Рахувати треба не на номінальні 14 В, а на НИЖНЮ
//  межу допуску живлення (CHARGE_PSU_MIN_MV = 12.5 В): струм бази падає разом
//  із живленням, а пік струму дроселя від нього майже не залежить.
//    150 Ом: 85 мА при 14 В, але лише 75 мА при 12.5 В — а на пік 1651 мА
//            потрібно 82 мА. Тобто просілий (та все ще ДОПУСТИМИЙ) блок
//            живлення виводив би ключ із насичення.
//    120 Ом: 94 мА при 12.5 В, 106 мА при 14 В, 123 мА при 16 В — насичення
//            тримається на всьому діапазоні, який прошивка приймає.
//  Перевірки наприкінці блока рахують ОБИДВІ межі діапазону, а не лише
//  номінал, і не дадуть зібрати прошивку, доки номінал не відповідає профілю.
//  Якщо 120 Ом дістати важко: 150 Ом лишається придатним, якщо знизити
//  CHARGE_MA_80 до 700 мА (пік 1351 мА -> потрібно 67 мА). Це на 40 % довший
//  заряд — вибір за власником, перевірки приймуть обидва варіанти.
//
//  ⚠️ Це ОДНА з ДВОХ замін; друга — 20 кОм -> 390 Ом у базі керуючого NPN
//  (див. CHARGE_NPN_BASE_OHM нижче). Поодинці жодна з них нічого не дає:
//  замінити тільки цей резистор означає попросити в NPN 106 мА, яких він при
//  20 кОм у базі віддати не може, і ключ однаково лишиться поза насиченням.
#define CHARGE_BASE_DRIVE_OHM   120
//  ⚠️ Розсіює Iб²×R×D — при 106 мА це ~0.83 Вт, тож резистор брати 2 Вт.
//  Майже ват, спалений просто на відкривання ключа, — це і є ціна БІПОЛЯРНОГО
//  верхнього ключа на такому струмі; з P-канальним MOSFET цієї статті витрат
//  не було б узагалі (затвор струму не споживає).
//  І NPN мусить пропускати ці 106 мА (при 16 В — 123 мА): BC547 (100 мА max)
//  не годиться, потрібен 2N2222 / BC337 / S8050.

// Падіння на переході база-емітер PNP і на насиченому NPN, мВ — для розрахунку
// струму бази.
