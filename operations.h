//  operations.h — ЄДИНИЙ КАТАЛОГ ОПЕРАЦІЙ для всіх поверхонь.
//
//  Раніше список дій дублювався у чотирьох місцях (екранне меню в display.h і
//  display_color.h, веб index.html, USB-клієнт client_usb.html + moto_gui.py) і
//  розходився: назви, порядок, попередження й навіть склад операцій відрізнялися.
//  Тепер список описано ТУТ, а поверхні його лише малюють:
//    • екранне меню бере назви/описи прямо з opInfo();
//    • веб і USB-клієнти отримують той самий каталог у JSON (/api/ops, OPS).
//
//  ПОРЯДОК — за реальним ходом ремонту, а не «як склалось історично»:
//
//    1. Заміна елементів     ← головна операція, тому перша
//    2. Глибока чистка
//    3. Ремонт цілісності
//    4. Заряд із напруги
//    5. Скидання лічильників
//    6. Очистка історії
//    7. Модель <X>           ← модельна частина еталона (по одній на шаблон)
//    8. Новий <X>            ← ініціалізація порожнього чипа
//    9. Стерти DS2433 / DS2438 / Перезавантаження   ← крайні випадки
//
//  Чому саме так — див. docs/FIRMWARE_ANALYSIS.md. Коротко: після заміни
//  елементів рація відкидає не «зіпсовану», а ЧУЖУ навчену калібровку, тож
//  ремонт — це СКИДАННЯ блока 0x18A..0x1FF у «чистий» вигляд (скелет записів
//  лишається, навчені значення обнуляються), а не запис чужого еталона й не
//  стирання в 0xFF: на стертому хвості ЗП не може завершити калібрування.
//  Тому «Заміна елементів» стоїть першою, а побайтове копіювання еталона
//  прибрано з екранного меню (лишилось у ручному режимі: RESTORE … VERBATIM).
// ===========================================================================

#include "templates.h"       // BATTERY_TEMPLATES / BATTERY_TEMPLATE_COUNT

// ---- рівень небезпеки ------------------------------------------------------
enum {
    OPD_SAFE   = 0,   // не змінює дані в чіпі
    OPD_WRITE  = 1,   // змінює дані, але зберігає ідентичність
    OPD_WIPE   = 2,   // незворотньо стирає ідентичність
};

// ---- стабільні коди базових операцій --------------------------------------
// Значення НЕ змінювати: вони їдуть у JSON і в команди USB-клієнта.
enum {
    OP_CELLSWAP      = 0,   // ремонт після заміни елементів
    OP_CELLSWAP_DEEP = 1,   // те саме + навчені записи ємності й журнал
    OP_REPAIR        = 2,   // ремонт цілісності (суми + дзеркало)
    OP_SETCHARGE     = 3,   // паливомір за напругою
    OP_RESET         = 4,   // обнулити лічильники
    OP_CLEAN         = 5,   // очистка історії
    OP_BASE_COUNT    = 6,
};

// Далі — по одній дії на шаблон:
//   [OP_BASE_COUNT               .. +COUNT-1] «Модель <X>»  (модельна частина)
//   [OP_BASE_COUNT + COUNT       .. +COUNT-1] «Новий <X>»   (порожній чіп -> АКБ)
// Потім три крайні операції.
inline int opModelBase()  { return OP_BASE_COUNT; }
inline int opNewBase()    { return OP_BASE_COUNT + BATTERY_TEMPLATE_COUNT; }
inline int opExpertBase() { return OP_BASE_COUNT + 2 * BATTERY_TEMPLATE_COUNT; }

enum { OP_WIPE33_REL = 0, OP_WIPE38_REL = 1, OP_REBOOT_REL = 2, OP_EXPERT_COUNT = 3 };

inline int opCount() { return opExpertBase() + OP_EXPERT_COUNT; }

// ---- розбір індексу --------------------------------------------------------
// Повертає індекс шаблону (0..COUNT-1) або -1.
inline int opTemplateOfModel(int sel) {
    int r = sel - opModelBase();
    return (r >= 0 && r < BATTERY_TEMPLATE_COUNT) ? r : -1;
}
inline int opTemplateOfNew(int sel) {
    int r = sel - opNewBase();
    return (r >= 0 && r < BATTERY_TEMPLATE_COUNT) ? r : -1;
}
// Повертає OP_WIPE33_REL/OP_WIPE38_REL/OP_REBOOT_REL або -1.
inline int opExpert(int sel) {
    int r = sel - opExpertBase();
    return (r >= 0 && r < OP_EXPERT_COUNT) ? r : -1;
}

// ---- описи для ЕКРАННОГО меню (коротко: 1 назва + 2 рядки) -----------------
