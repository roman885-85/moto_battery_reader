// ===========================================================================
//  РОЗРЯДНА НАВАНТАГА (MOSFET + резистор) — керований розряд пакета.
// ===========================================================================
//  ДЛЯ ЧОГО. Після ремонту зарядна станція не бере АКБ на калібрування, якщо
//  бачить його зарядженим: світить зеленим і просто тримає. Контрольований
//  розряд до ~7.2 В прибирає цю невизначеність — станція зобов'язана піти в
//  повний цикл. Другий зиск: за час розряду рахуємо РЕАЛЬНУ ємність нових
//  банок (приймальний контроль після перепайки).
//
//  СХЕМА. N-канальний MOSFET у НИЖНЬОМУ ключі (логічний рівень, відкривається
//  позитивним потенціалом на затворі):
//
//      +АКБ --[ R_load 5 Ом / 25 Вт ]-- D
//                                       |
//                                    MOSFET (N-ch, logic level)
//                                       |
//      -АКБ --------------------------- S -- спільна земля з ESP32
//                          G -- LOAD_PIN
//                          +--[ 10 кОм ]-- GND     <-- ОБОВ'ЯЗКОВО
//
//  !! РЕЗИСТОР 10 кОм ІЗ ЗАТВОРА НА ЗЕМЛЮ ОБОВ'ЯЗКОВИЙ. Під час скидання й
//  завантаження ESP32 піни у високоімпедансному стані: без підтяжки затвор
//  «висить», MOSFET може лишитися відкритим і посадити пакет у нуль. Програмних
//  запобіжників тут НЕ досить — потрібен саме апаратний резистор.
//
//  ПОТУЖНІСТЬ. «Голий» струм на 5 Ом: 8.4 В -> 1.68 А -> 14.1 Вт; 7.0 В ->
//  1.40 А -> 9.8 Вт. Стільки ми НЕ беремо: струм обмежується ШІМом (нижче), тож
//  середня потужність на резисторі ~5..8 Вт. Запас усе одно потрібен — резистор
//  на 25 Вт із радіатором: під час вимірювання піка (див. нижче) ключ на
//  короткий час відкривається повністю.
//
//  MOSFET працює КЛЮЧЕМ: або повністю відкритий, або повністю закритий. ШІМ це
//  не порушує — між станами ключ проскакує за мікросекунди, у лінійному режимі
//  (де вихід за SOA) він не затримується. Через це затвор бажано підключати
//  через резистор 100 Ом послідовно: він гасить дзвін і бере на себе кидок
//  струму перезаряду затвора, який інакше йде з піна ESP32.
//
//  ВИМІР СТРУМУ. Свій шунт не потрібен: струмовимірювальний резистор DS2438
//  стоїть УСЕРЕДИНІ пакета послідовно з банками, тож увесь наш струм проходить
//  через нього й видно у регістрі струму та в лічильнику DCA.
//
//  Розряд ВИМКНЕНО, доки не задано LOAD_PIN.
// ---------------------------------------------------------------------------
#define LOAD_PIN 19        // затвор MOSFET. GPIO18/23 зайняті SPI дисплея,
                           // 34..39 — лише вхід, GPIO0 — strapping (підтяжка
                           // затвора не дала б завантажитись). Лишається 19.
                           // Закоментуйте рядок, щоб вимкнути функцію розряду.

// Опір навантаження, Ом — для оцінки струму «на повністю відкритому ключі»
// (початкове наближення ШІМ до першого виміру). На облік мА*год не впливає:
// він рахується з РЕАЛЬНОГО струму DS2438.
#define LOAD_OHM            5.0f

// ---------------------------------------------------------------------------
//  ОБМЕЖЕННЯ СТРУМУ ШІМом
// ---------------------------------------------------------------------------
//  Навіщо. На 5 Ом «голий» струм — 1.4..1.7 А. Це і забагато для резистора, і
//  забагато для щойно перепаяних банок: 1.7 А на пакеті 2.15 А*год — це 0.8C,
//  на такому струмі просадка напруги велика, вимір ємності занижується, а банки
//  й контакти гріються дарма. Тому ключ керується ШІМом, а не просто «увімк.».
//
//  Яку уставку тримаємо. Не одну — струм веде за напругою ЛІНІЙНО:
//
//      DISCHARGE_RAMP_HI_MV -> DISCHARGE_MA_HI (1000 мА)   ← повний заряд
//         ...          лінійно          ...
//      ЦІЛЬОВА напруга      -> DISCHARGE_MA_LO (300 мА)    ← кінець розряду
//
//  Так зроблено тому, що просадка під навантаженням найбільше спотворює саме
//  кінець розряду: на розрядженому пакеті внутрішній опір вищий, і великий
//  струм передчасно «продавлює» напругу до цілі — розряд обірветься раніше, ніж
//  банки насправді віддадуть ємність. Малий струм у кінці дає чесніший вимір і
//  щадить банки. Поза відрізком уставка тримається на межах (не екстраполюємо).
//
//  ⚑ НИЗ ЛІНІЙКИ ЇДЕ ЗА ЦІЛЛЮ. Ціль розряду задається користувачем, і лінійка
//  будується під неї: 300 мА досягаються РІВНО на обраній цілі, хоч 7.2 В, хоч
//  7.6 В. Інакше при цілі 7.8 В розряд закінчувався б на 550 мА, тобто якраз на
//  тому струмі, який і спотворює вимір.
