#ifndef COMBO_H
#define COMBO_H
// ===========================================================================
//  combo.h — КОМБІНАЦІЇ КНОПОК (чиста логіка, без екрана й Arduino)
// ===========================================================================
//  У пристрою три кнопки, і всі три вже зайняті звичайною навігацією. Коли
//  треба ще один вхід — увімкнути чи вимкнути цілу функцію, — окремої кнопки
//  для нього немає й не буде. Такий вхід роблять КОМБІНАЦІЄЮ: послідовністю
//  натискань, яку неможливо набрати випадково, гортаючи меню.
//
//  Тут лежить рівно те, що можна перевірити на хості: коли комбінація
//  вважається набраною, а коли ланцюжок обривається. Обидва драйвери екрана
//  (display.h і display_color.h) на хості не збираються, тому все, що вміє
//  жити окремо від них, живе окремо.
//
//  ⚑ ЧОМУ «ШВИДКО» — ЧАСТИНА УМОВИ, А НЕ ЗРУЧНІСТЬ. Без обмеження за часом
//  «чотири натискання OK» означало б «чотири натискання OK коли завгодно»:
//  людина гортає меню, час від часу тисне OK — і рано чи пізно вимикає собі
//  заряд, не зрозумівши, що зробила. Пауза довша за COMBO_GAP_MS рве ланцюжок,
//  і саме це робить комбінацію навмисною.
// ===========================================================================

#include <stdint.h>

// Найбільша пауза МІЖ сусідніми натисканнями ланцюжка. 600 мс — це помітно
// швидше за спокійне гортання й водночас не вимагає спритності.
#ifndef COMBO_GAP_MS
  #define COMBO_GAP_MS 600u
#endif

// Клавіші в комбінаціях. Значення довільні, аби стабільні: вони їдуть у
// таблиці візерунків нижче.
enum { CK_NONE = 0, CK_LEFT = 1, CK_RIGHT = 2, CK_OK = 3 };

// ── N ШВИДКИХ НАТИСКАНЬ ОДНІЄЇ КЛАВІШІ ────────────────────────────────────
struct ComboTap { uint8_t n = 0; uint32_t last = 0; };

// Порядковий номер натискання в поточному ланцюжку: 1, 2, 3 … Пауза довша за
// gapMs починає ланцюжок заново, тобто повертає 1.
//
//  ⚑ ПОВЕРТАЄМО НОМЕР, А НЕ «ТАК/НІ». Виклик має знати не лише про останнє
//  натискання ланцюжка, а й про СЕРЕДИНУ: другому й третьому натисканню
//  звичайну дію виконувати не можна. Інакше дорога до комбінації проходила б
//  через «відкрити меню, виконати пункт, виконати пункт» — тобто набрати її
//  означало б спершу щось накоїти.
inline uint8_t comboTapCount(ComboTap &c, uint32_t now, uint32_t gapMs) {
    if (c.n && (uint32_t)(now - c.last) <= gapMs) {
        if (c.n < 255) c.n++;
    } else {
        c.n = 1;
    }
    c.last = now;
    return c.n;
}
inline void comboTapReset(ComboTap &c) { c.n = 0; c.last = 0; }

// ── ПОСЛІДОВНІСТЬ РІЗНИХ КЛАВІШ ───────────────────────────────────────────
struct ComboSeq { uint8_t n = 0; uint32_t last = 0; };

// Найдовший ВЛАСНИЙ префікс візерунка, який водночас є суфіксом уже набраних
// n клавіш. Це відкат Кнута—Морріса—Пратта, лише порахований на місці: сам
// візерунок — сім елементів, і чесний перебір тут дешевший за таблицю, яку
// довелося б тримати в узгодженні з ним.
inline uint8_t comboSeqFallback(const uint8_t *pat, uint8_t n) {
    for (uint8_t k = n ? n - 1 : 0; k > 0; k--) {
        bool pref = true;
        for (uint8_t i = 0; i < k; i++)
            if (pat[n - k + i] != pat[i]) { pref = false; break; }
        if (pref) return k;
    }
    return 0;
}

// Подати натиснуту клавішу. Повертає true рівно тоді, коли щойно набрано
// ВЕСЬ візерунок.
//
//  ⚑ ХИБНА КЛАВІША НЕ ОБНУЛЯЄ ЛІК, А ВІДКОЧУЄ ЙОГО. Різниця видима саме на
//  нашому візерунку, бо він починається з ПОВТОРУ («‹ ‹ › › ‹ ‹ OK»). Людина,
//  що зайвий раз натисне «‹» на початку, набирає «‹ ‹ ‹ › › ‹ ‹ OK». Скидання
//  «в нуль» тут програє: третє «‹» лишило б лік на одиниці, і всі наступні
//  клавіші лягли б не на свої місця. Відкат бачить, що два останніх «‹» — це
//  й є перші дві клавіші візерунка, і лік лишається двійкою.
//
//  Спершу цей відкат був написаний «як здається»: не збіглось — почати з цієї
//  ж клавіші, якщо вона перша у візерунку. Тест на зайве натискання його й
//  завалив. Половинчасте правило гірше за очевидно просте: воно виглядає
//  продуманим і тому не викликає підозр.
inline bool comboSeqFeed(ComboSeq &c, uint32_t now, uint8_t key,
                         const uint8_t *pat, uint8_t patN, uint32_t gapMs) {
    if (!pat || patN == 0) return false;
    if (c.n && (uint32_t)(now - c.last) > gapMs) c.n = 0;   // задовга пауза
    c.last = now;
    uint8_t n = c.n;
    while (n > 0 && !(n < patN && key == pat[n])) n = comboSeqFallback(pat, n);
    if (n < patN && key == pat[n]) n++;
    c.n = n;
    if (c.n == patN) { c.n = 0; return true; }
    return false;
}
inline void comboSeqReset(ComboSeq &c) { c.n = 0; c.last = 0; }

// ── ОБИДВІ КОМБІНАЦІЇ РАЗОМ, ОДНИМ РІШЕННЯМ ───────────────────────────────
//  Драйверів екрана два (монохромний і кольоровий), і жоден не збирається на
//  хості. Якби кожен вирішував сам, чи вважати натискання частиною
//  комбінації, правило існувало б у двох копіях — і розійшлося б на першій же
//  правці. Тому рішення тут, у чистій функції, а драйвери лише виконують
//  його: показати повідомлення, перемкнути заряд або пропустити далі.
enum {
    CMB_PASS   = 0,   // звичайне натискання, обробляйте як завжди
    CMB_EAT    = 1,   // середина ланцюжка — НЕ виконувати звичайну дію
    CMB_TOGGLE = 2,   // набрано «увімкнути/вимкнути заряд»
    CMB_FLASH  = 3,   // набрано приховану комбінацію
};

// Скільки швидких натискань вимикають (і вмикають назад) заряд.
#ifndef COMBO_TAPS_CHARGE
  #define COMBO_TAPS_CHARGE 4
#endif

static const uint8_t COMBO_FLASH_PAT[] = {
    CK_LEFT, CK_LEFT, CK_RIGHT, CK_RIGHT, CK_LEFT, CK_LEFT, CK_OK
};
#define COMBO_FLASH_LEN ((uint8_t)(sizeof(COMBO_FLASH_PAT) / sizeof(COMBO_FLASH_PAT[0])))

struct ComboState { ComboTap tap; ComboSeq seq; };

// Розірвати обидва ланцюжки. Кличеться на ДОВГЕ натискання: комбінація — це
// серія коротких, і утримання кнопки її не продовжує.
inline void comboBreak(ComboState &s) { comboTapReset(s.tap); comboSeqReset(s.seq); }

// key — щойно натиснута клавіша (CK_*), readKey — та, на якій висить вимикач
// заряду (у різних складаннях це різні кнопки: там, де кнопок дві, окремого
// «OK» немає).
inline uint8_t comboFeed(ComboState &s, uint32_t now, uint8_t key, uint8_t readKey) {
    if (comboSeqFeed(s.seq, now, key, COMBO_FLASH_PAT, COMBO_FLASH_LEN, COMBO_GAP_MS)) {
        comboTapReset(s.tap);
        return CMB_FLASH;
    }
    if (key != readKey) { comboTapReset(s.tap); return CMB_PASS; }
    uint8_t n = comboTapCount(s.tap, now, COMBO_GAP_MS);
    if (n >= COMBO_TAPS_CHARGE) { comboTapReset(s.tap); return CMB_TOGGLE; }
    // Друге й третє натискання ланцюжка звичайної дії НЕ виконують — інакше
    // дорога до вимикача проходила б через «відкрити меню, натиснути пункт».
    return (n > 1) ? CMB_EAT : CMB_PASS;
}

// ── ПОВНОЕКРАННЕ ПОВІДОМЛЕННЯ НА ЗАДАНИЙ ЧАС ──────────────────────────────
#ifndef COMBO_FLASH_MS
  #define COMBO_FLASH_MS 5000u
#endif

struct ComboFlash { uint32_t until = 0; };

inline void comboFlashArm(ComboFlash &f, uint32_t now, uint32_t ms) {
    f.until = now + ms;
    if (f.until == 0) f.until = 1;      // 0 зарезервовано під «не показуємо»
}
inline bool comboFlashActive(const ComboFlash &f, uint32_t now) {
    return f.until != 0 && (int32_t)(now - f.until) < 0;
}
// true РІВНО ОДИН РАЗ — на тому проході, коли час вийшов. Саме на ньому
// драйвер і перемальовує екран назад; питати «чи вже минуло» щопроходу й
// перемальовувати щоразу означало б вічну перемальовку.
inline bool comboFlashExpired(ComboFlash &f, uint32_t now) {
    if (f.until == 0) return false;
    if ((int32_t)(now - f.until) < 0) return false;
    f.until = 0;
    return true;
}

#endif // COMBO_H
