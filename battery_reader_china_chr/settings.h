// ── ПІДТЯЖКА ЛІНІЇ ДАНИХ 1-Wire ───────────────────────────────────────────
//  ⚠️⚠️ ЗОВНІШНІЙ РЕЗИСТОР 2.2…4.7 кОм З ЛІНІЇ ДАНИХ НА 3.3 В ОБОВ'ЯЗКОВИЙ.
//  Внутрішня підтяжка ESP32 (~45 кОм) його НЕ ЗАМІНЮЄ, і це не питання запасу.
//  DS2433 і DS2438 живляться ПАРАЗИТНО — струм на власну роботу вони беруть із
//  тієї самої лінії даних у паузах між бітами. 45 кОм від 3.3 В дають десятки
//  мікроамперів; чипу цього не вистачає навіть щоб утримати внутрішнє
//  живлення, тож він не відповідає взагалі. Симптом — «акумулятор не
//  зчитується» при цілком справному коді.
//  У попередній редакції тут було написано, що внутрішньої досить. Це
//  неправильно: вона рятує лише від «лінія висить у повітрі», але не годиться
//  як джерело живлення для чипів.
//
//  DS_INTERNAL_PULLUP лишається УВІМКНЕНОЮ як другорядний запобіжник (паралельно
//  зовнішньому резистору вона нічого не змінює), і має неочевидну пастку, яку
//  варто знати.
//
//  ⚠️ ПАСТКА. Внутрішня підтяжка — це окреме налаштування піна, і воно
//  ВИМИКАЄТЬСЯ будь-яким pinMode(pin, INPUT): у arduino-esp32 INPUT (0x01) не
//  містить біта PULLUP (0x04), тож виклик явно знімає підтяжку. А конструктор
//  бібліотеки OneWire робить рівно це — pinMode(pin, INPUT). Далі бібліотека
//  чіпає лише регістр дозволу виходу (щоб «відпустити» лінію), налаштування
//  підтяжки не відновлює ніколи — і лінія просто висить у повітрі.
//  Тому прошивка вмикає внутрішню підтяжку ЯВНО, ПІСЛЯ конструктора OneWire
//  (BatteryReader::dsIdle()), і повертає її після кожної діагностики.
//
//  Значення 0 вимикає внутрішню підтяжку. Робити це немає причин: паралельно
//  зовнішньому резистору вона нічого не псує, а без неї лінія в паузах між
//  операціями лишається зовсім без опори.
